function npmProject(deps, src) {
  const pkg = { name: "svc", version: "1.0.0", private: true, main: "index.js", dependencies: Object.fromEntries(Object.entries(deps).map(([k, v]) => [k, v.spec ?? v.version])) };
  const lock = { name: "svc", version: "1.0.0", lockfileVersion: 3, requires: true, packages: { "": { name: "svc", version: "1.0.0", dependencies: pkg.dependencies } } };
  for (const [k, v] of Object.entries(deps)) lock.packages[`node_modules/${k}`] = { version: v.version, resolved: `https://registry.npmjs.org/${k}/-/${k.split("/").pop()}-${v.version}.tgz` };
  return { "package.json": JSON.stringify(pkg, null, 2) + "\n", "package-lock.json": JSON.stringify(lock, null, 2) + "\n", "index.js": src };
}
function pyProject(lines, src) {
  return { "requirements.txt": lines.join("\n") + "\n", "app.py": src };
}
function cargoProject(deps, src) {
  const toml = `[package]\nname = "svc"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\n` + Object.entries(deps).map(([k, v]) => `${k} = ${v.toml ?? `"${v.version}"`}`).join("\n") + "\n";
  const lock = `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n` +
    Object.entries(deps).map(([k, v]) => `[[package]]\nname = "${k}"\nversion = "${v.version}"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n`).join("\n") +
    `\n[[package]]\nname = "svc"\nversion = "0.1.0"\ndependencies = [\n${Object.keys(deps).map((k) => ` "${k}",`).join("\n")}\n]\n`;
  return { "Cargo.toml": toml, "Cargo.lock": lock, "src/main.rs": src };
}
function goProject(reqs, src) {
  const mod = `module example.com/svc\n\ngo 1.22\n\nrequire (\n${Object.entries(reqs).map(([k, v]) => `\t${k} ${v}`).join("\n")}\n)\n`;
  return { "go.mod": mod, "main.go": src };
}

