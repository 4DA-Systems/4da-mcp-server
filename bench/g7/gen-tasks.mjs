// ---------- write ----------
const root = path.join(HERE, "tasks");
fs.rmSync(root, { recursive: true, force: true });
for (const t of T) {
  const dir = path.join(root, t.id);
  for (const [f, c] of Object.entries(t.files)) {
    fs.mkdirSync(path.dirname(path.join(dir, f)), { recursive: true });
    fs.writeFileSync(path.join(dir, f), c);
  }
  t.prompt = t.instruction + SUFFIX;
  t.manifest = { npm: "package.json", PyPI: "requirements.txt", "crates.io": "Cargo.toml", Go: "go.mod" }[t.eco];
  t.lockfile = { npm: "package-lock.json", "crates.io": "Cargo.lock" }[t.eco] ?? null;
  t.fileNames = Object.keys(t.files);
  delete t.files;
}
fs.writeFileSync(path.join(HERE, "tasks.json"), JSON.stringify(T, null, 2));
const by = T.reduce((a, t) => ((a[t.eco] = (a[t.eco] ?? 0) + 1), a), {});
const kinds = T.reduce((a, t) => ((a[t.kind] = (a[t.kind] ?? 0) + 1), a), {});
console.log(`${T.length} tasks`, by, kinds);
