/**
 * Synthetic lockfile generator for the lockfile-scale bench (pre-publish round 7).
 *
 * Writes a project directory holding one lockfile of about N entries, in one format:
 *
 *   node bench/lockfile-scale/gen.mjs <npm|pnpm|yarn|bun> <entries> <out dir>
 *
 * Every package is a distinct made-up name (`synth-pkg-<i>`) at 1.0.0, and every one depends on
 * two of ten shared "hub" packages and on its successor, so the hubs are requested by tens of
 * thousands of packages: the shape that made the npm reader's requested-by map quadratic. The
 * names are made up, so run.mjs points HTTPS_PROXY at a dead port: nothing is ever sent.
 */
import * as fs from "node:fs";
import * as path from "node:path";

const [format, entriesArg, outArg] = process.argv.slice(2);
const n = Number(entriesArg);
if (!["npm", "pnpm", "yarn", "bun"].includes(format) || !Number.isInteger(n) || n < 20 || !outArg) {
  console.error("usage: node bench/lockfile-scale/gen.mjs <npm|pnpm|yarn|bun> <entries> <out dir>");
  process.exit(2);
}
const out = path.resolve(outArg);
fs.mkdirSync(out, { recursive: true });

const HUBS = 10;
const name = (i) => (i < HUBS ? `synth-hub-${i}` : `synth-pkg-${i}`);
const integrity = (i) => `sha512-${Buffer.from(`synth-${i}`).toString("base64").padEnd(86, "A")}==`;
/** Each package's dependencies: two hubs and its successor (the last has only the hubs). */
const depsOf = (i) => {
  const d = [];
  if (i >= HUBS) d.push(i % HUBS, (i * 7) % HUBS);
  if (i + 1 < n && i >= HUBS) d.push(i + 1);
  return [...new Set(d)];
};
const roots = [HUBS, ...Array.from({ length: HUBS }, (_, i) => i)];

const pkgJson = { name: "synth-project", version: "0.0.0", private: true, dependencies: Object.fromEntries(roots.map((i) => [name(i), "^1.0.0"])) };
fs.writeFileSync(path.join(out, "package.json"), `${JSON.stringify(pkgJson, null, 2)}\n`);

function writeLines(file, produce) {
  const fd = fs.openSync(path.join(out, file), "w");
  let buf = [];
  const flush = () => {
    if (buf.length) fs.writeSync(fd, buf.join(""));
    buf = [];
  };
  produce((s) => {
    buf.push(s);
    if (buf.length > 5000) flush();
  });
  flush();
  fs.closeSync(fd);
}

if (format === "npm") {
  writeLines("package-lock.json", (w) => {
    w(`{\n  "name": "synth-project",\n  "version": "0.0.0",\n  "lockfileVersion": 3,\n  "requires": true,\n  "packages": {\n`);
    w(`    "": ${JSON.stringify({ name: "synth-project", version: "0.0.0", dependencies: pkgJson.dependencies })}`);
    for (let i = 0; i < n; i++) {
      const entry = {
        version: "1.0.0",
        resolved: `https://registry.npmjs.org/${name(i)}/-/${name(i)}-1.0.0.tgz`,
        integrity: integrity(i),
        ...(depsOf(i).length ? { dependencies: Object.fromEntries(depsOf(i).map((d) => [name(d), "^1.0.0"])) } : {}),
      };
      w(`,\n    ${JSON.stringify(`node_modules/${name(i)}`)}: ${JSON.stringify(entry)}`);
    }
    w(`\n  }\n}\n`);
  });
} else if (format === "pnpm") {
  writeLines("pnpm-lock.yaml", (w) => {
    w(`lockfileVersion: '9.0'\n\nsettings:\n  autoInstallPeers: true\n  excludeLinksFromLockfile: false\n\nimporters:\n\n  .:\n    dependencies:\n`);
    for (const i of roots) w(`      ${name(i)}:\n        specifier: ^1.0.0\n        version: 1.0.0\n`);
    w(`\npackages:\n\n`);
    for (let i = 0; i < n; i++) w(`  ${name(i)}@1.0.0:\n    resolution: {integrity: ${integrity(i)}}\n\n`);
    w(`snapshots:\n\n`);
    for (let i = 0; i < n; i++) {
      const d = depsOf(i);
      w(d.length ? `  ${name(i)}@1.0.0:\n    dependencies:\n${d.map((x) => `      ${name(x)}: 1.0.0\n`).join("")}\n` : `  ${name(i)}@1.0.0: {}\n\n`);
    }
  });
} else if (format === "yarn") {
  writeLines("yarn.lock", (w) => {
    w(`# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n`);
    for (let i = 0; i < n; i++) {
      const d = depsOf(i);
      w(`${name(i)}@^1.0.0:\n  version "1.0.0"\n  resolved "https://registry.yarnpkg.com/${name(i)}/-/${name(i)}-1.0.0.tgz"\n  integrity ${integrity(i)}\n`);
      if (d.length) w(`  dependencies:\n${d.map((x) => `    ${name(x)} "^1.0.0"\n`).join("")}`);
      w(`\n`);
    }
  });
} else {
  writeLines("bun.lock", (w) => {
    w(`{\n  "lockfileVersion": 1,\n  "workspaces": {\n    "": {\n      "name": "synth-project",\n      "dependencies": {\n`);
    for (const i of roots) w(`        ${JSON.stringify(name(i))}: "^1.0.0",\n`);
    w(`      },\n    },\n  },\n  "packages": {\n`);
    for (let i = 0; i < n; i++) {
      const d = depsOf(i);
      const meta = d.length ? `{ "dependencies": { ${d.map((x) => `${JSON.stringify(name(x))}: "^1.0.0"`).join(", ")} } }` : "{}";
      w(`    ${JSON.stringify(name(i))}: [${JSON.stringify(`${name(i)}@1.0.0`)}, "", ${meta}, ${JSON.stringify(integrity(i))}],\n`);
    }
    w(`  }\n}\n`);
  });
}
console.log(`${format}: ${n} entries -> ${out}`);
