/**
 * pnpm at a workspace root, and Yarn Berry everywhere, keep the locked copy for every requiring edge
 * the step does not name, even when that edge's range admits the fix. Audit 2026-11-25, Track B:
 *
 * - vue core v3.2.47 (pnpm workspace): the plan's minimist row said `pnpm update minimist --no-save`
 *   fixes minimist 1.2.5; after the run json5 1.0.2 still resolved minimist 1.2.5 (critical
 *   GHSA-xvch-5gv4-984h). Measured 2026-11-26 on its real lockfile, scripts off, pnpm 7.33.7 and
 *   10.34.6: `pnpm update minimist --no-save` and `... --depth Infinity --no-save` left json5's edge
 *   on 1.2.5; `pnpm update -r minimist --depth Infinity --no-save` moved every edge to 1.2.8 and left
 *   every package.json as it was (the same without --no-save rewrote the root's ^1.2.0 to ^1.2.8).
 *   In a project that is no workspace, pnpm 7 and 10 moved the json5 edge with the root's own
 *   `pnpm update minimist --no-save` or `pnpm up minimist@1.2.6`: nothing changes there.
 * - redux-toolkit v1.9.0 (Yarn 3.2.4): `yarn workspace docs add "nanoid@^3.3.18"` left
 *   "nanoid@npm:^3.1.23, nanoid@npm:^3.3.4" on 3.3.4 (4 advisories); followed by `yarn up -R nanoid`
 *   every descriptor resolved to 3.3.20.
 *
 * So for those managers the row also runs the manager's own refresh of every edge, after the step,
 * when each other edge's requirement resolves to a clean release at or above the target; when one
 * does not, or that cannot be established, the row says which copy stays and is not counted as fixed.
 */

import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { adv, createHarness, fixedIn, type Harness } from "./helpers/a1119-planner-harness.js";

let h: Harness;
beforeEach(() => {
  h = createHarness();
});
afterEach(() => h.dispose());

const reasonsOf = (step: Record<string, any>) => (step.reasons as string[]).join(" | ");
type Step = { n: number; dir: string; run: string; fixes: string[] };

function pnpmWorkspace(): void {
  h.ADVISORIES = { minimist: [adv("GHSA-xvch-5gv4-984h", "minimist", fixedIn("1.2.6"), "npm", "CRITICAL")] };
  h.NPM = {
    minimist: { latest: "1.2.8", versions: { "1.2.5": {}, "1.2.6": {}, "1.2.8": {} } },
    json5: { latest: "1.0.2", versions: { "1.0.1": { dependencies: { minimist: "^1.2.0" } }, "1.0.2": { dependencies: { minimist: "^1.2.0" } } } },
  };
  h.write("package.json", JSON.stringify({ name: "vue", private: true, devDependencies: { minimist: "^1.2.0" } }));
  h.write("pnpm-workspace.yaml", "packages:\n  - 'packages/*'\n");
  h.write("packages/compiler/package.json", JSON.stringify({ name: "compiler", version: "1.0.0", devDependencies: { json5: "1.0.1" } }));
  h.write(
    "pnpm-lock.yaml",
    [
      "lockfileVersion: '9.0'",
      "",
      "importers:",
      "",
      "  .:",
      "    devDependencies:",
      "      minimist:",
      "        specifier: ^1.2.0",
      "        version: 1.2.5",
      "",
      "  packages/compiler:",
      "    devDependencies:",
      "      json5:",
      "        specifier: 1.0.1",
      "        version: 1.0.1",
      "",
      "packages:",
      "",
      "  json5@1.0.1:",
      "    resolution: {integrity: sha512-json5}",
      "",
      "  minimist@1.2.5:",
      "    resolution: {integrity: sha512-minimist}",
      "",
      "snapshots:",
      "",
      "  json5@1.0.1:",
      "    dependencies:",
      "      minimist: 1.2.5",
      "",
      "  minimist@1.2.5: {}",
      "",
    ].join("\n"),
  );
}

function berryProject(nanoidVersions: string[], extra: Record<string, ReturnType<typeof adv>[]> = {}): void {
  h.ADVISORIES = { nanoid: [adv("GHSA-mwcw-c2x4-8c55", "nanoid", fixedIn("3.3.8"), "npm", "MODERATE")], ...extra };
  h.NPM = {
    nanoid: { latest: nanoidVersions[nanoidVersions.length - 1], versions: Object.fromEntries(nanoidVersions.map((v) => [v, {}])) },
    postcss: { latest: "8.4.14", versions: { "8.4.14": { dependencies: { nanoid: "^3.3.4" } } } },
  };
  h.write("package.json", JSON.stringify({ name: "app", version: "1.0.0", dependencies: { nanoid: "3.3.4", postcss: "8.4.14" } }));
  h.write(
    "yarn.lock",
    [
      '# This file is generated by running "yarn install" inside your project.',
      "# Manual changes might be lost - proceed with caution!",
      "",
      "__metadata:",
      "  version: 6",
      "  cacheKey: 8",
      "",
      '"app@workspace:.":',
      "  version: 0.0.0-use.local",
      '  resolution: "app@workspace:."',
      "  dependencies:",
      "    nanoid: 3.3.4",
      "    postcss: 8.4.14",
      "  languageName: unknown",
      "  linkType: soft",
      "",
      '"nanoid@npm:3.3.4, nanoid@npm:^3.3.4":',
      "  version: 3.3.4",
      '  resolution: "nanoid@npm:3.3.4"',
      "  checksum: 0123",
      "  languageName: node",
      "  linkType: hard",
      "",
      '"postcss@npm:8.4.14":',
      "  version: 8.4.14",
      '  resolution: "postcss@npm:8.4.14"',
      "  dependencies:",
      "    nanoid: ^3.3.4",
      "  checksum: 0123",
      "  languageName: node",
      "  linkType: hard",
      "",
    ].join("\n"),
  );
}

describe("pnpm at a workspace root: a copy another importer's package also holds", () => {
  it("the direct refresh is followed by the recursive refresh of every edge (vue core minimist via json5)", async () => {
    pnpmWorkspace();
    const { result, step } = await h.plan();
    const row = step("minimist");
    expect(row.upgradeCommands).toEqual([{ dir: ".", command: "pnpm update minimist --no-save", refresh: true }]);
    expect(row.refreshCommands).toEqual([{ dir: ".", command: "pnpm update -r minimist --depth Infinity --no-save" }]);
    expect(reasonsOf(row)).toContain("json5 1.0.1 (\"^1.2.0\") also holds minimist 1.2.5: at a pnpm workspace root pnpm keeps that locked copy when only the declared entry moves, so this row also runs `pnpm update -r minimist --depth Infinity --no-save`, which resolves their requirement to minimist 1.2.8 (no advisory affects it)");
    const runs = (result.run_order as Step[]).map((s) => s.run);
    const direct = runs.indexOf("pnpm update minimist --no-save");
    const refresh = runs.indexOf("pnpm update -r minimist --depth Infinity --no-save");
    expect(direct).toBeGreaterThanOrEqual(0);
    expect(refresh).toBeGreaterThan(direct);
    expect((result.run_order as Step[])[refresh].fixes).toContain("npm:minimist");
  });

  it("names the hand step and does not count the row as fixed when the other edge's refresh lands on an affected release", async () => {
    pnpmWorkspace();
    // 1.2.8, the newest release json5's "^1.2.0" admits, is affected by a second advisory.
    h.ADVISORIES.minimist.push(adv("GHSA-0000-late-0001", "minimist", [{ introduced: "1.2.7" }, { fixed: "1.2.9" }]));
    const { result, step } = await h.plan();
    const row = step("minimist");
    expect(row.refreshCommands ?? []).toEqual([]);
    expect(reasonsOf(row)).toMatch(/^.*Other packages that use this copy of minimist keep one on its old line after this upgrade: json5 1\.0\.1 \("\^1\.2\.0"\) keeps minimist 1\.2\.5, the copy its lockfile entry holds/);
    expect(reasonsOf(row)).toContain("a refresh of its requirement resolves to minimist 1.2.8, which an advisory affects (GHSA-0000-late-0001)");
    expect((result.run_order as Step[]).some((s) => s.fixes.includes("npm:minimist"))).toBe(false);
  });

  it("a pnpm project that is no workspace is unchanged: the root's own step moves the edge", async () => {
    pnpmWorkspace();
    h.write("pnpm-workspace.yaml", "");
    const fs = await import("node:fs");
    const path = await import("node:path");
    fs.rmSync(path.join(h.dir, "pnpm-workspace.yaml"));
    const { step } = await h.plan();
    const row = step("minimist");
    expect(row.refreshCommands ?? []).toEqual([]);
    expect(reasonsOf(row)).not.toMatch(/also holds minimist|Other packages that use this copy/);
  });
});

describe("Yarn Berry: another descriptor of the same copy", () => {
  it("the step is followed by `yarn up -R` (redux-toolkit nanoid)", async () => {
    berryProject(["3.3.4", "3.3.8", "3.3.11"]);
    const { result, step } = await h.plan();
    const row = step("nanoid");
    expect(row.upgradeCommands).toEqual([{ dir: ".", command: "yarn up nanoid@3.3.8" }]);
    expect(row.refreshCommands).toEqual([{ dir: ".", command: "yarn up -R nanoid" }]);
    expect(reasonsOf(row)).toContain("postcss 8.4.14 (\"^3.3.4\") also holds nanoid 3.3.4: Yarn Berry keeps that locked copy when only the declared entry moves, so this row also runs `yarn up -R nanoid`, which resolves their requirement to nanoid 3.3.11 (no advisory affects it)");
    const runs = (result.run_order as Step[]).map((s) => s.run);
    expect(runs.indexOf("yarn up -R nanoid")).toBeGreaterThan(runs.indexOf("yarn up nanoid@3.3.8"));
  });

  it("an in-range refresh that is already `yarn up -R` needs nothing more", async () => {
    berryProject(["3.3.4", "3.3.8", "3.3.11"]);
    h.write("package.json", JSON.stringify({ name: "app", version: "1.0.0", dependencies: { nanoid: "^3.3.4", postcss: "8.4.14" } }));
    const { step } = await h.plan();
    const row = step("nanoid");
    expect(row.upgradeCommands).toEqual([{ dir: ".", command: "yarn up -R nanoid", refresh: true }]);
    expect(row.refreshCommands ?? []).toEqual([]);
  });

  it("not counted as fixed when the other edge's refresh lands on an affected release", async () => {
    berryProject(["3.3.4", "3.3.8", "3.3.11"], { nanoid: [adv("GHSA-mwcw-c2x4-8c55", "nanoid", fixedIn("3.3.8"), "npm", "MODERATE"), adv("GHSA-0000-late-0002", "nanoid", [{ introduced: "3.3.10" }, { fixed: "3.3.12" }])] });
    const { result, step } = await h.plan();
    const row = step("nanoid");
    expect(row.refreshCommands ?? []).toEqual([]);
    expect(reasonsOf(row)).toContain("postcss 8.4.14 (\"^3.3.4\") keeps nanoid 3.3.4, the copy its lockfile entry holds (Yarn Berry keeps a locked copy when only the declared entry moves), and a refresh of its requirement resolves to nanoid 3.3.11, which an advisory affects (GHSA-0000-late-0002)");
    expect(row.upgradeInstructions).toEqual([{ dir: ".", instruction: "after upgrading nanoid, the copy of nanoid 3.3.4 that postcss keeps remains: move it by hand (an override, or an upgrade of that package), then run vulnerability_scan" }]);
    expect((result.run_order as Step[]).some((s) => s.fixes.includes("npm:nanoid"))).toBe(false);
  });
});

describe("pnpm at a workspace root: a requirement that cannot be read", () => {
  it("is not taken as shared: the row is not counted as fixed", async () => {
    pnpmWorkspace();
    // pnpm lockfiles record no ranges; the registry has no json5 1.0.1 to read the range from.
    h.NPM.json5 = { latest: "1.0.2", versions: { "1.0.2": { dependencies: { minimist: "^1.2.0" } } } };
    const { result, step } = await h.plan();
    const row = step("minimist");
    expect(row.refreshCommands ?? []).toEqual([]);
    expect(reasonsOf(row)).toMatch(/Other packages that use this copy of minimist keep one on its old line after this upgrade: .*json5 1\.0\.1 \(its requirement could not be read\)/);
    expect((result.run_order as Step[]).some((s) => s.fixes.includes("npm:minimist"))).toBe(false);
  });
});
