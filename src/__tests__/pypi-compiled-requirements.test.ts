/**
 * Audit 6.2.5 A-4: reading a compiled requirements file (`uv pip compile`, `pip-compile`): the
 * tool, the input it was compiled from, and each pin's `# via` reason, in the forms the tools
 * write; the scanner's direct set and directFix's hand edit both honour it, and the re-compile
 * advice splices only plain tokens into a command (audit C-1).
 */

import { describe, it, expect, beforeEach, afterEach } from "vitest";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { compiledIndirect, compiledRequiredBy, compiledRequirements } from "../live/lockfile-parsers-pygo.js";
import { pypiDirectInstruction } from "../live/fix-paths.js";
import { pypiCompiledInstruction, pypiPinnedTogether } from "../live/pypi-advice.js";
import { requirementNamesWithIncludes } from "../project-manifests.js";

const UV = `# This file was autogenerated by uv via the following command:
#    uv pip compile requirements.in -o requirements.txt --python-version 3.8
idna==2.7
    # via requests
requests==2.19.1
    # via -r requirements.in
`;

describe("compiledRequirements", () => {
  it("uv: the tool and the input named in its header command", () => {
    const c = compiledRequirements(UV)!;
    expect(c.tool).toBe("uv");
    expect(c.input).toBe("requirements.in");
    expect(compiledIndirect(c, "idna")).toBe(true);
    expect(compiledIndirect(c, "requests")).toBe(false);
    expect(compiledRequiredBy(c, "IDNA")).toEqual(["requests"]);
  });

  it("pip-compile 7: `--output-file=` is not the input; pip-compile 5's `To update, run:` with `--output-file x` is not either", () => {
    const seven = "#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n#    pip-compile --output-file=requirements.txt requirements.in\n#\nidna==2.7\n    # via requests\n";
    expect(compiledRequirements(seven)).toMatchObject({ tool: "pip-compile", input: "requirements.in" });
    const five = "#\n# This file is autogenerated by pip-compile\n# To update, run:\n#\n#    pip-compile --output-file requirements.txt requirements.in\n#\nidna==2.7                 # via requests\nflask==1.0 # via -r requirements.in\n";
    const c = compiledRequirements(five)!;
    expect(c).toMatchObject({ tool: "pip-compile", input: "requirements.in" });
    expect(compiledIndirect(c, "idna")).toBe(true);
    expect(compiledIndirect(c, "flask")).toBe(false);
  });

  it("a custom compile script (CTFd's ./scripts/pip-compile.sh): the input comes from the `# via -r` annotations", () => {
    const ctfd = "#\n# This file is autogenerated by pip-compile with python 3.9\n# To update, run:\n#\n#    ./scripts/pip-compile.sh\n#\nalembic==1.4.3\n    # via\n    #   dataset\n    #   flask-migrate\nbcrypt==3.1.7\n    # via -r requirements.in\n";
    const c = compiledRequirements(ctfd)!;
    expect(c.input).toBe("requirements.in");
    expect(compiledIndirect(c, "alembic")).toBe(true);
    expect(compiledRequiredBy(c, "alembic")).toEqual(["dataset", "flask-migrate"]);
  });

  it("a pyproject input (`# via myproj (pyproject.toml)`) is declared, and a `-c` constraint alone is not a reason", () => {
    const body = "anyio==4.0.0\n    # via\n    #   -c constraints.txt\n    #   httpx\nhttpx==0.27.0\n    # via myproj (pyproject.toml)\n";
    const c = compiledRequirements(body)!;
    expect(c.tool).toBeNull();
    expect(c.input).toBe("pyproject.toml");
    expect(compiledIndirect(c, "httpx")).toBe(false);
    expect(compiledIndirect(c, "anyio")).toBe(true);
  });

  it("a hand-written file is not compiled; a pin with no annotation is never called indirect", () => {
    expect(compiledRequirements("django==4.2  # LTS\nrequests==2.31.0\n")).toBeNull();
    const c = compiledRequirements("# This file was autogenerated by uv via the following command:\n#    uv pip compile requirements.in\nfoo==1.0\n")!;
    expect(compiledIndirect(c, "foo")).toBe(false);
  });
});

describe("the hand edit and the direct set honour a compiled file", () => {
  let dir: string;
  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), "4da-pypi-compiled-unit-"));
  });
  afterEach(() => fs.rmSync(dir, { recursive: true, force: true }));

  it("directFix names no hand edit of `uv pip compile` output (the old check knew only pip-compile's header)", () => {
    expect(pypiDirectInstruction(UV, "requirements.txt", "idna", "2.7", "3.15")).toBeNull();
    expect(pypiDirectInstruction(UV, "requirements.txt", "requests", "2.19.1", "2.33.0")).toBeNull();
  });

  it("the scanner's direct names leave out `# via` pins (transitive, as go.mod's // indirect)", () => {
    fs.writeFileSync(path.join(dir, "requirements.txt"), UV);
    expect(requirementNamesWithIncludes(path.join(dir, "requirements.txt"), dir)).toEqual(["requests"]);
  });

  it("a target that is not a plain token is never spliced into the command", () => {
    fs.writeFileSync(path.join(dir, "requirements.in"), "requests==2.19.1\n");
    fs.writeFileSync(path.join(dir, "requirements.txt"), UV);
    const text = pypiCompiledInstruction(dir, "idna", "2.7", '3.15"; rm -rf ~; "')!;
    expect(text).not.toContain("rm -rf");
    expect(text).not.toMatch(/`uv pip compile requirements/);
    expect(text).toMatch(/an `--upgrade-package` option for it/);
  });

  it("no joint-resolution sentence for a single pin, a compiled file, or a file with a range", () => {
    fs.writeFileSync(path.join(dir, "requirements.txt"), "django==4.2\n");
    expect(pypiPinnedTogether(dir, "django", "4.2")).toBeNull();
    fs.writeFileSync(path.join(dir, "requirements.txt"), UV);
    expect(pypiPinnedTogether(dir, "requests", "2.19.1")).toBeNull();
    fs.writeFileSync(path.join(dir, "requirements.txt"), "django==4.2\nasgiref~=3.6\n");
    expect(pypiPinnedTogether(dir, "django", "4.2")).toBeNull();
    fs.writeFileSync(path.join(dir, "requirements.txt"), "-r base.txt\ndjango==4.2 ; python_version >= '3.8'\nasgiref==3.6.0  # pinned\n");
    expect(pypiPinnedTogether(dir, "django", "4.2")).toMatch(/^requirements\.txt pins every requirement exactly/);
  });
});
