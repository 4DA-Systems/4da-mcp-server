/**
 * A dependency a Yarn workspace member declares is moved where it is declared, as for npm and
 * pnpm members: the fix step names the member's directory and the command that acts on that
 * workspace only. `yarn workspace <name> add <spec>` was run against yarn 1.22.22 and 4.9.1 on a
 * two-member workspace (minimist and ms from the public registry, 2026-11-19): it moved only the
 * named member's declaration, keeping its section and operator (yarn 1 needs `--dev` /
 * `--optional` for those sections: its `upgrade` in a member wrote a devDependency into
 * `dependencies`; yarn 4's `up` rewrote the sibling's `~0.0.8` too). When the declaring member
 * cannot be established, the step says so and names no directory.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import Database from "better-sqlite3";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { directFix } from "../live/fix-paths.js";
import { LiveIntelligence } from "../live/index.js";
import { scanProjectTree, treeResolutionGroups } from "../project-tree.js";
import { executeUpgradePlanner } from "../tools/upgrade-planner.js";
import { executeVulnerabilityScan } from "../tools/vulnerability-scan.js";
import { npmAdvisory, removeProject, stubOsv, tempProject, type NpmDoc } from "./helpers/a1119-readers.js";

const MINIMIST = npmAdvisory("GHSA-xvch-5gv4-984h", "minimist", "0.2.4", "CRITICAL");
const MINIMIST_DOC: NpmDoc = { latest: "1.2.8", versions: { "0.0.8": {}, "0.0.10": {}, "0.2.4": {}, "1.2.8": {} } };

const CLASSIC_LOCK = (entries: Record<string, string>) =>
  [
    "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
    "# yarn lockfile v1",
    "",
    "",
    ...Object.entries(entries).flatMap(([key, version]) => [
      `${key}:`,
      `  version "${version}"`,
      `  resolved "https://registry.yarnpkg.com/${key.split("@")[0]}/-/${key.split("@")[0]}-${version}.tgz"`,
      "  integrity sha512-AAAA",
      "",
    ]),
  ].join("\n");

function berryLock(workspaces: Record<string, { name: string; deps: Record<string, string> }>, packages: Record<string, string>): string {
  const lines = ['# This file is generated by running "yarn install" inside your project.', "# Manual changes might be lost - proceed with caution!", "", "__metadata:", "  version: 8", "  cacheKey: 10c0", ""];
  for (const [dir, ws] of Object.entries(workspaces)) {
    lines.push(`"${ws.name}@workspace:${dir}":`, "  version: 0.0.0-use.local", `  resolution: "${ws.name}@workspace:${dir}"`);
    if (Object.keys(ws.deps).length > 0) {
      lines.push("  dependencies:");
      for (const [dep, spec] of Object.entries(ws.deps)) lines.push(`    ${dep}: "npm:${spec}"`);
    }
    lines.push("  languageName: unknown", "  linkType: soft", "");
  }
  for (const [spec, version] of Object.entries(packages)) {
    const name = spec.slice(0, spec.indexOf("@", 1));
    lines.push(`"${name}@npm:${spec.slice(name.length + 1)}":`, `  version: ${version}`, `  resolution: "${name}@npm:${version}"`, "  checksum: 10c0/0123456789abcdef", "  languageName: node", "  linkType: hard", "");
  }
  return lines.join("\n");
}

const ROOT = JSON.stringify({ name: "root", private: true, workspaces: ["packages/*"] });
const API = JSON.stringify({ name: "api", version: "1.0.0", devDependencies: { minimist: "0.0.8" } });
const WEB = JSON.stringify({ name: "@demo/web", version: "1.0.0", dependencies: { minimist: "~0.0.8" } });

const CLASSIC = {
  "package.json": ROOT,
  "packages/api/package.json": API,
  "packages/web/package.json": WEB,
  "yarn.lock": CLASSIC_LOCK({ "minimist@0.0.8": "0.0.8", "minimist@~0.0.8": "0.0.10" }),
};

const BERRY = {
  "package.json": ROOT,
  "packages/api/package.json": API,
  "packages/web/package.json": WEB,
  "yarn.lock": berryLock(
    { ".": { name: "root", deps: {} }, "packages/api": { name: "api", deps: { minimist: "0.0.8" } }, "packages/web": { name: "@demo/web", deps: { minimist: "~0.0.8" } } },
    { "minimist@0.0.8": "0.0.8", "minimist@~0.0.8": "0.0.10" },
  ),
};

function liveFor(dir: string): LiveIntelligence {
  const live = new LiveIntelligence(new Database(":memory:"));
  const { entries, discovery } = scanProjectTree(dir);
  live.initFromProjectTree(dir, treeResolutionGroups(entries), discovery);
  return live;
}

async function plan(dir: string, live = liveFor(dir)): Promise<Record<string, any>> {
  return (await executeUpgradePlanner(null as never, { project_path: dir } as never, live)) as Record<string, any>;
}

async function scan(dir: string, format: "detailed" | "concise", live = liveFor(dir)): Promise<Record<string, any>> {
  return (await executeVulnerabilityScan(null, { project_path: dir, response_format: format }, live)) as Record<string, any>;
}

const rowOf = (answer: Record<string, any>, version: string) => answer.recommendations.find((r: { package: string; currentVersion: string }) => r.package === "minimist" && r.currentVersion === version);

describe("a Yarn workspace member's dependency moves in that member", () => {
  let dirs: string[];
  let priorOffline: string | undefined;
  const project = (files: Record<string, string>) => {
    const dir = tempProject(files);
    dirs.push(dir);
    return dir;
  };

  beforeEach(() => {
    dirs = [];
    priorOffline = process.env.FOURDA_OFFLINE;
    delete process.env.FOURDA_OFFLINE;
  });

  afterEach(() => {
    vi.unstubAllGlobals();
    if (priorOffline === undefined) delete process.env.FOURDA_OFFLINE;
    else process.env.FOURDA_OFFLINE = priorOffline;
    dirs.forEach(removeProject);
  });

  for (const [kind, files, apiCommand, webCommand] of [
    ["classic", CLASSIC, "yarn workspace api add minimist@0.2.4 --dev", 'yarn workspace @demo/web add "minimist@~0.2.4"'],
    ["berry", BERRY, "yarn workspace api add minimist@0.2.4", 'yarn workspace @demo/web add "minimist@~0.2.4"'],
  ] as const) {
    it(`${kind}: the plan names each declaring member's directory and its workspace command`, async () => {
      stubOsv([MINIMIST], { minimist: MINIMIST_DOC });
      const dir = project(files);
      const answer = await plan(dir);
      const api = rowOf(answer, "0.0.8");
      expect(api).toMatchObject({ scope: "direct", action: "upgrade_direct", targetVersion: "0.2.4" });
      expect(api.upgradeCommands).toEqual([{ dir: "packages/api", command: apiCommand }]);
      expect(api.reasons.join(" ")).toMatch(/Declared by workspace member packages\/api\/package\.json \(devDependencies "0\.0\.8"\), not by the project root/);
      const web = rowOf(answer, "0.0.10");
      expect(web.upgradeCommands).toEqual([{ dir: "packages/web", command: webCommand }]);
      expect(web.reasons.join(" ")).toMatch(/Declared by workspace member packages\/web\/package\.json \(dependencies "~0\.0\.8"\)/);
    });

    it(`${kind}: vulnerability_scan gives the plan's commands, in both formats`, async () => {
      stubOsv([MINIMIST], { minimist: MINIMIST_DOC });
      const dir = project(files);
      const detailed = await scan(dir, "detailed");
      expect(detailed.fix_targets["minimist@0.0.8"]).toMatchObject({ target: "0.2.4", action: "upgrade_direct", commands: [{ dir: "packages/api", command: apiCommand }] });
      expect(detailed.fix_targets["minimist@0.0.10"]).toMatchObject({ commands: [{ dir: "packages/web", command: webCommand }] });
      // The concise answer's line names where it moves, as the plan's commands do, not where it is locked.
      const lines = (await scan(dir, "concise")).recommendations as string[];
      expect(lines.find((l) => l.includes("minimist 0.0.8"))).toMatch(/^Upgrade minimist 0\.0\.8 → 0\.2\.4 in packages\/api — .*Declared by workspace member packages\/api\/package\.json/);
      expect(lines.find((l) => l.includes("minimist 0.0.10"))).toMatch(/^Upgrade minimist 0\.0\.10 → 0\.2\.4 in packages\/web — /);
    });
  }

  it("directFix names the workspace form only for a member of the Yarn workspace above it", () => {
    const dir = project({ ...CLASSIC, "packages/other/package.json": JSON.stringify({ name: "other", dependencies: { minimist: "0.0.8" } }), "tools/x/package.json": JSON.stringify({ name: "x", dependencies: { minimist: "0.0.8" } }) });
    expect(directFix(path.join(dir, "packages", "api"), "npm", "minimist", "0.0.8", "0.2.4")).toEqual({ command: "yarn workspace api add minimist@0.2.4 --dev" });
    // Not a member (no workspace pattern names tools/x): `yarn workspace x` would not find it.
    expect(directFix(path.join(dir, "tools", "x"), "npm", "minimist", "0.0.8", "0.2.4")).toBeNull();
    // A declaration with no readable operator names nothing, as for npm and pnpm.
    fs.writeFileSync(path.join(dir, "packages", "other", "package.json"), JSON.stringify({ name: "other", dependencies: { minimist: ">=0.0.8" } }));
    expect(directFix(path.join(dir, "packages", "other"), "npm", "minimist", "0.0.8", "0.2.4")).toBeNull();
    // A member name a shell would read specially is never spliced into a command.
    fs.writeFileSync(path.join(dir, "packages", "other", "package.json"), JSON.stringify({ name: "a;rm -rf x", dependencies: { minimist: "0.0.8" } }));
    expect(directFix(path.join(dir, "packages", "other"), "npm", "minimist", "0.0.8", "0.2.4")).toBeNull();
  });

  it("the root and a member both declaring it: each moves where it is declared", async () => {
    stubOsv([MINIMIST], { minimist: MINIMIST_DOC });
    const dir = project({ ...CLASSIC, "package.json": JSON.stringify({ name: "root", private: true, workspaces: ["packages/*"], dependencies: { minimist: "0.0.8" } }) });
    const api = rowOf(await plan(dir), "0.0.8");
    expect(api.upgradeCommands).toEqual([
      { dir: ".", command: "yarn upgrade minimist@0.2.4" },
      { dir: "packages/api", command: "yarn workspace api add minimist@0.2.4 --dev" },
    ]);
    expect(api.reasons.join(" ")).toMatch(/Also declared by workspace member packages\/api\/package\.json \(devDependencies "0\.0\.8"\)/);
  });

  it("when the declaring member cannot be established, the step says so and names no directory", async () => {
    stubOsv([MINIMIST], { minimist: MINIMIST_DOC });
    const dir = project(CLASSIC);
    const live = liveFor(dir);
    // The member's manifest became unreadable after the scan read it.
    fs.writeFileSync(path.join(dir, "packages", "api", "package.json"), "{ not json");
    const api = rowOf(await plan(dir, live), "0.0.8");
    expect(api.scope).toBe("direct");
    expect(api.upgradeCommands).toBeUndefined();
    expect(api.reasons.join(" ")).toMatch(/workspace member that declares it could not be established \(packages\/api\/package\.json could not be read\)/);
    expect(JSON.stringify(api)).not.toMatch(/"dir":"packages\/api"/);
  });
});
