/**
 * Audit 6.2.5 A-4: PyPI advice, executed as written, left requirements that did not install.
 *
 * - A `uv pip compile` / `pip-compile` output was edited by hand: its `# via requests` pins were
 *   labelled direct and told "change `idna==2.7` to `idna==3.15` in requirements.txt", which
 *   requests 2.19.1 (`idna<2.8`) refused. A compiled file is moved by re-compiling its input with
 *   `--upgrade-package`, and an indirect pin is transitive.
 * - A flat file that pins everything: each `==` edit read as safe on its own, but Django 5.2.17
 *   needs asgiref>=3.8.1 while asgiref==3.6.0 is pinned. The edits are said to need re-resolving.
 *
 * End to end through upgrade_planner and vulnerability_scan, with OSV and PyPI stubbed. Only the
 * tools' public entry points are imported, so these run (and fail) on the code before the fix.
 */

import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import Database from "better-sqlite3";
import { LiveIntelligence } from "../live/index.js";
import type { OsvVulnerability } from "../live/types.js";
import { executeVulnerabilityScan } from "../tools/vulnerability-scan.js";
import { executeUpgradePlanner } from "../tools/upgrade-planner.js";
import type { FourDADatabase } from "../db.js";

const noDb = null as unknown as FourDADatabase;

const pyAdv = (id: string, name: string, fixed: string): OsvVulnerability => ({
  id,
  aliases: [],
  summary: `${name} advisory ${id}`,
  database_specific: { severity: "HIGH" },
  affected: [{ package: { name, ecosystem: "PyPI" }, ranges: [{ type: "ECOSYSTEM", events: [{ introduced: "0" }, { fixed }] }] }],
});

let ADVISORIES: Record<string, OsvVulnerability[]> = {};
let RELEASES: Record<string, string[]> = {};

const cmp = (a: string, b: string) => a.localeCompare(b, undefined, { numeric: true });
const affects = (v: OsvVulnerability, version: string) => cmp(version, v.affected![0].ranges[0].events.find((e) => e.fixed)!.fixed!) < 0;

function stubNetwork() {
  vi.stubGlobal("fetch", async (input: string | URL, init?: RequestInit) => {
    const url = String(input);
    const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });
    if (url.endsWith("/v1/querybatch")) {
      const { queries } = JSON.parse(String(init?.body)) as { queries: Array<{ package: { name: string }; version: string }> };
      return json({ results: queries.map((q) => ({ vulns: (ADVISORIES[q.package.name] ?? []).filter((v) => affects(v, q.version)).map((v) => ({ id: v.id })) })) });
    }
    if (url.includes("/v1/vulns/")) {
      const id = decodeURIComponent(url.split("/v1/vulns/")[1]);
      const found = Object.values(ADVISORIES).flat().find((v) => v.id === id);
      return found ? json(found) : json({}, 404);
    }
    if (url === "https://api.osv.dev/v1/query") {
      const q = JSON.parse(String(init?.body)) as { package: { name: string } };
      return json({ vulns: ADVISORIES[q.package.name] ?? [] });
    }
    const pypi = /^https:\/\/pypi\.org\/pypi\/([^/]+)\/json$/.exec(url);
    if (pypi) {
      const name = decodeURIComponent(pypi[1]).toLowerCase();
      const versions = RELEASES[name];
      if (!versions) return json({}, 404);
      const releases = Object.fromEntries(versions.map((v) => [v, [{ upload_time_iso_8601: "2024-01-01T00:00:00Z", yanked: false }]]));
      return json({ info: { name, version: versions[versions.length - 1], license: "", classifiers: [], summary: "", yanked: false, yanked_reason: null }, releases });
    }
    return json({}, 404);
  });
}

let dir: string;
let priorOffline: string | undefined;

beforeEach(() => {
  priorOffline = process.env.FOURDA_OFFLINE;
  delete process.env.FOURDA_OFFLINE;
  dir = fs.mkdtempSync(path.join(os.tmpdir(), "4da-pypi-compiled-"));
  ADVISORIES = {
    idna: [pyAdv("PYSEC-2024-60", "idna", "3.15")],
    requests: [pyAdv("PYSEC-2023-74", "requests", "2.33.0")],
    django: [pyAdv("PYSEC-2025-1", "django", "5.2.17")],
  };
  RELEASES = {
    idna: ["2.7", "3.4", "3.15"],
    requests: ["2.19.1", "2.33.0"],
    django: ["4.2", "5.2.17"],
    asgiref: ["3.6.0", "3.8.1"],
    certifi: ["2019.3.9"],
    jinja2: ["2.10.1"],
  };
  stubNetwork();
});

afterEach(() => {
  vi.unstubAllGlobals();
  if (priorOffline === undefined) delete process.env.FOURDA_OFFLINE;
  else process.env.FOURDA_OFFLINE = priorOffline;
  fs.rmSync(dir, { recursive: true, force: true });
});

const write = (file: string, body: string) => fs.writeFileSync(path.join(dir, file), body);

/** Track A's hb-f6b fixture: `uv pip compile requirements.in -o requirements.txt`. */
const UV_COMPILED = `# This file was autogenerated by uv via the following command:
#    uv pip compile requirements.in -o requirements.txt --exclude-newer 2019-06-01 --python-version 3.8
certifi==2019.3.9
    # via requests
idna==2.7
    # via requests
jinja2==2.10.1
    # via -r requirements.in
requests==2.19.1
    # via -r requirements.in
`;

/** pip-tools 7.6.2's header and annotations, as it wrote them for the same input (2026-10-26). */
const PIP_COMPILED = `#
# This file is autogenerated by pip-compile with Python 3.12
# by the following command:
#
#    pip-compile --output-file=requirements.txt requirements.in
#
certifi==2019.3.9
    # via requests
idna==2.7
    # via requests
jinja2==2.10.1
    # via -r requirements.in
requests==2.19.1
    # via -r requirements.in
`;

async function plan() {
  const li = new LiveIntelligence(new Database(":memory:"));
  const { scanProjectTree, treeResolutionGroups } = await import("../project-tree.js");
  const { entries, discovery } = scanProjectTree(dir);
  li.initFromProjectTree(dir, treeResolutionGroups(entries), discovery);
  const result = (await executeUpgradePlanner(noDb, { project_path: dir, max_recommendations: 50 }, li)) as Record<string, any>;
  const step = (name: string) => result.recommendations.find((s: { package: string }) => s.package === name);
  return { result, step };
}

const scan = async () => (await executeVulnerabilityScan(null, { project_path: dir }, new LiveIntelligence(new Database(":memory:")))) as Record<string, any>;
const instructionOf = (step: { upgradeInstructions?: Array<{ instruction: string }> }) => (step.upgradeInstructions ?? []).map((i) => i.instruction).join(" | ");

describe("audit 6.2.5 A-4: a uv-compiled requirements file is re-compiled, never hand-edited", () => {
  beforeEach(() => {
    write("requirements.in", "jinja2<2.11\nrequests==2.19.1\n");
    write("requirements.txt", UV_COMPILED);
  });

  it("an indirect pin (`# via requests`) is transitive and names the re-compile with the checked target", async () => {
    const { step } = await plan();
    const idna = step("idna");
    expect(idna).toMatchObject({ scope: "transitive", targetVersion: "3.15" });
    const text = instructionOf(idna);
    expect(text).toContain('`uv pip compile requirements.in -o requirements.txt --upgrade-package "idna==3.15"`');
    expect(text).toMatch(/idna is not declared: requirements\.txt is compiled by `uv pip compile` from requirements\.in and pins it only because requests requires it/);
    expect(text).toMatch(/The resolver refuses when requests excludes 3\.15/);
    expect(text).not.toMatch(/change `idna==2\.7`/);
    expect(idna.reasons.join(" ")).toMatch(/compiled requirements file pins it only because other packages require it/);
  });

  it("a declared pin of a compiled file points at the input and re-compiles, never edits the output", async () => {
    const { step } = await plan();
    const requests = step("requests");
    expect(requests).toMatchObject({ scope: "direct", action: "upgrade_direct", targetVersion: "2.33.0" });
    const text = instructionOf(requests);
    expect(text).toMatch(/make sure the requests requirement in requirements\.in admits 2\.33\.0/);
    expect(text).toContain('`uv pip compile requirements.in -o requirements.txt --upgrade-package "requests==2.33.0"`');
    expect(text).not.toMatch(/change `requests==2\.19\.1`/);
    expect(requests.upgradeCommands).toBeUndefined();
  });

  it("vulnerability_scan reports the indirect pin as transitive and says to re-compile", async () => {
    const result = await scan();
    const idna = result.vulnerable_packages.find((p: { package: string }) => p.package === "idna");
    expect(idna.is_direct).toBe(false);
    const line = result.recommendations.find((r: string) => r.startsWith("Upgrade idna"));
    expect(line).toMatch(/requirements\.txt is compiled from requirements\.in: re-compile it with --upgrade-package instead of editing it \(it is pinned only because other packages require it\)/);
  });
});

describe("audit 6.2.5 A-4: pip-compile output names pip-compile's own re-compile", () => {
  it("reads the input from the header's `--output-file=` form and names `pip-compile ... --upgrade-package`", async () => {
    write("requirements.in", "jinja2<2.11\nrequests==2.19.1\n");
    write("requirements.txt", PIP_COMPILED);
    const { step } = await plan();
    expect(step("idna")).toMatchObject({ scope: "transitive" });
    expect(instructionOf(step("idna"))).toContain('`pip-compile requirements.in --output-file requirements.txt --upgrade-package "idna==3.15"`');
    expect(instructionOf(step("requests"))).toContain('`pip-compile requirements.in --output-file requirements.txt --upgrade-package "requests==2.33.0"`');
  });

  it("an input outside the project or absent is never echoed into a command", async () => {
    write("requirements.txt", PIP_COMPILED.replace("requirements.in", "../outside/requirements.in"));
    const { step } = await plan();
    const text = instructionOf(step("idna"));
    expect(text).not.toContain("outside");
    expect(text).not.toMatch(/`pip-compile [^`]*`/);
    expect(text).toMatch(/re-compile it from its input with `--upgrade-package "idna==3\.15"` instead of editing it/);
  });
});

describe("audit 6.2.5 A-4: `==` edits of a fully pinned file are not presented as independently safe", () => {
  it("pygoat's shape: the Django edit says the file's pin changes must be re-resolved together", async () => {
    write("requirements.txt", "asgiref==3.6.0\nDjango==4.2\nidna==3.4\n");
    const { step } = await plan();
    const text = instructionOf(step("django"));
    expect(text).toMatch(/^change `Django==4\.2` to `Django==5\.2\.17` in requirements\.txt; requirements\.txt pins every requirement exactly, so this edit is not safe on its own/);
    expect(text).toContain("`uv pip compile requirements.txt`");
    expect(text).toContain("`pip install --dry-run -r requirements.txt`");
    const result = await scan();
    expect(result.recommendations.find((r: string) => r.startsWith("Upgrade django"))).toMatch(/requirements\.txt pins every requirement exactly: re-resolve it with the other pin changes before installing/);
  });

  it("a file with a range among its requirements keeps the plain edit (no joint-resolution claim)", async () => {
    write("requirements.txt", "asgiref>=3.6\nDjango==4.2\n");
    const { step } = await plan();
    expect(instructionOf(step("django"))).toBe("change `Django==4.2` to `Django==5.2.17` in requirements.txt");
  });
});
