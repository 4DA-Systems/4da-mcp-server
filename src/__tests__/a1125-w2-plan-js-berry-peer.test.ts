/**
 * Yarn Berry refuses `yarn add <pkg>` when the manifest also lists <pkg> under peerDependencies:
 * "Package "graphql" is already listed as a peer dependency - use either of -D or -P" (exit 1).
 * Audit 2026-11-25, Track B: redux-toolkit v1.9.0's packages/rtk-query-graphql-request-base-query
 * declares graphql as peer AND dev, and the plan's `yarn workspace @rtk-query/graphql-request-base-query
 * add "graphql@^16.8.1"` failed. Measured 2026-11-26, scripts off, `--mode update-lockfile`:
 *
 *   yarn 3.2.4 / 4.9.1  workspace <m> add "graphql@^16.8.1"         exit 1 (Usage Error above)
 *   yarn 3.2.4 / 4.9.1  workspace <m> add "graphql@^16.8.1" --dev   exit 0, devDependencies ^16.8.1, peer range unchanged
 *   yarn 3.2.4 / 4.9.1  add "ms@^2.1.3" (dev + peer)                exit 1;  with --dev: exit 0, peer unchanged
 *   yarn 3.2.4 / 4.9.1  up "ms@^2.1.3" (dev + peer)                 exit 0, devDependencies ^2.1.3, peer unchanged
 *   yarn 4.9.1          add "ms@^2.1.3" [--optional] (dependencies or optionalDependencies + peer)   exit 1
 *
 * So a Berry add for a dev dependency the manifest also lists as a peer carries `--dev`; one for a
 * dependency or optional dependency that is also a peer has no `yarn add` that works, and the plan
 * names no command for it (its reasons keep the hand step). Yarn 1 is unchanged.
 */

import * as path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { directFix } from "../live/fix-paths.js";
import { parseCommand } from "../tools/upgrade-plan-sequence.js";
import { removeProject, tempProject } from "./helpers/a1119-readers.js";

function berryLock(workspaces: Record<string, { name: string; deps: Record<string, string> }>, packages: Record<string, string>): string {
  const lines = ['# This file is generated by running "yarn install" inside your project.', "# Manual changes might be lost - proceed with caution!", "", "__metadata:", "  version: 6", "  cacheKey: 8", ""];
  for (const [dir, ws] of Object.entries(workspaces)) {
    lines.push(`"${ws.name}@workspace:${dir}":`, "  version: 0.0.0-use.local", `  resolution: "${ws.name}@workspace:${dir}"`);
    if (Object.keys(ws.deps).length > 0) {
      lines.push("  dependencies:");
      for (const [dep, spec] of Object.entries(ws.deps)) lines.push(`    ${dep}: ${spec}`);
    }
    lines.push("  languageName: unknown", "  linkType: soft", "");
  }
  for (const [spec, version] of Object.entries(packages)) {
    const name = spec.slice(0, spec.indexOf("@", 1));
    lines.push(`"${name}@npm:${spec.slice(name.length + 1)}":`, `  version: ${version}`, `  resolution: "${name}@npm:${version}"`, "  checksum: 0123456789abcdef", "  languageName: node", "  linkType: hard", "");
  }
  return lines.join("\n");
}

const CLASSIC_LOCK = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\ngraphql@^16.5.0:\n  version "16.5.0"\n  resolved "https://registry.yarnpkg.com/graphql/-/graphql-16.5.0.tgz"\n  integrity sha512-AAAA\n';

const PEER = "^0.13.0 || ^14.0.0 || ^15.0.0 || ^16.0.0";

function workspace(member: Record<string, unknown>, lock: "berry" | "classic" = "berry"): string {
  return tempProject({
    "package.json": JSON.stringify({ name: "rtk-monorepo", private: true, workspaces: ["packages/*"] }),
    "packages/gql/package.json": JSON.stringify({ name: "@rtk-query/graphql-request-base-query", version: "2.0.0", ...member }),
    "yarn.lock":
      lock === "berry"
        ? berryLock(
            { ".": { name: "rtk-monorepo", deps: {} }, "packages/gql": { name: "@rtk-query/graphql-request-base-query", deps: { graphql: "^16.5.0" } } },
            { "graphql@^16.5.0": "16.5.0" },
          )
        : CLASSIC_LOCK,
  });
}

describe("Yarn Berry: a package the manifest also lists as a peer", () => {
  const dirs: string[] = [];
  const keep = (dir: string) => (dirs.push(dir), dir);
  afterEach(() => dirs.splice(0).forEach(removeProject));

  it("a member's dev dependency that is also a peer is moved with --dev (redux-toolkit graphql)", () => {
    const dir = keep(workspace({ peerDependencies: { graphql: PEER }, devDependencies: { graphql: "^16.5.0" } }));
    expect(directFix(path.join(dir, "packages", "gql"), "npm", "graphql", "16.5.0", "16.8.1")).toEqual({
      command: 'yarn workspace @rtk-query/graphql-request-base-query add "graphql@^16.8.1" --dev',
    });
  });

  it("a member's dependency or optional dependency that is also a peer gets no command: no yarn add moves it", () => {
    for (const section of ["dependencies", "optionalDependencies"]) {
      const dir = keep(workspace({ peerDependencies: { graphql: PEER }, [section]: { graphql: "^16.5.0" } }));
      expect(directFix(path.join(dir, "packages", "gql"), "npm", "graphql", "16.5.0", "16.8.1")).toBeNull();
    }
  });

  it("a member's dev dependency with no peer entry is unchanged (no flag on Berry)", () => {
    const dir = keep(workspace({ devDependencies: { graphql: "^16.5.0" } }));
    expect(directFix(path.join(dir, "packages", "gql"), "npm", "graphql", "16.5.0", "16.8.1")).toEqual({
      command: 'yarn workspace @rtk-query/graphql-request-base-query add "graphql@^16.8.1"',
    });
  });

  it("Yarn 1 keeps its own flags: --dev for a dev dependency whether or not it is a peer", () => {
    const dir = keep(workspace({ peerDependencies: { graphql: PEER }, devDependencies: { graphql: "^16.5.0" } }, "classic"));
    expect(directFix(path.join(dir, "packages", "gql"), "npm", "graphql", "16.5.0", "16.8.1")).toEqual({
      command: 'yarn workspace @rtk-query/graphql-request-base-query add "graphql@^16.8.1" --dev',
    });
  });

  it("at a Berry workspace root, `yarn add` for a dev dependency that is also a peer carries --dev; a dependency that is also a peer gets none", () => {
    const root = (manifest: Record<string, unknown>) =>
      keep(
        tempProject({
          "package.json": JSON.stringify({ name: "root", private: true, workspaces: ["packages/*"], ...manifest }),
          "packages/a/package.json": JSON.stringify({ name: "a", version: "1.0.0" }),
          "yarn.lock": berryLock({ ".": { name: "root", deps: { ms: "~2.0.0" } }, "packages/a": { name: "a", deps: {} } }, { "ms@~2.0.0": "2.0.0" }),
        }),
      );
    expect(directFix(root({ peerDependencies: { ms: "*" }, devDependencies: { ms: "~2.0.0" } }), "npm", "ms", "2.0.0", "2.1.3")).toEqual({ command: 'yarn add "ms@~2.1.3" --dev' });
    expect(directFix(root({ peerDependencies: { ms: "*" }, dependencies: { ms: "~2.0.0" } }), "npm", "ms", "2.0.0", "2.1.3")).toBeNull();
    // No peer entry: unchanged.
    expect(directFix(root({ devDependencies: { ms: "~2.0.0" } }), "npm", "ms", "2.0.0", "2.1.3")).toEqual({ command: 'yarn add "ms@~2.1.3"' });
  });

  it("a Berry project that is no workspace keeps `yarn up`, which moves a dev dependency listed as a peer too", () => {
    const dir = keep(
      tempProject({
        "package.json": JSON.stringify({ name: "p", version: "1.0.0", peerDependencies: { ms: "*" }, devDependencies: { ms: "~2.0.0" } }),
        "yarn.lock": berryLock({ ".": { name: "p", deps: { ms: "~2.0.0" } } }, { "ms@~2.0.0": "2.0.0" }),
      }),
    );
    expect(directFix(dir, "npm", "ms", "2.0.0", "2.1.3")).toEqual({ command: 'yarn up "ms@~2.1.3"' });
  });

  it("the sequencer reads a root `yarn add ... --dev` as a version-setting step", () => {
    expect(parseCommand('yarn add "ms@~2.1.3" --dev')).toMatchObject({ kind: "set", tool: "yarn", pkg: "ms", version: "2.1.3" });
    expect(parseCommand('yarn workspace @rtk-query/graphql-request-base-query add "graphql@^16.8.1" --dev')).toMatchObject({ kind: "set", tool: "yarn", pkg: "graphql", version: "16.8.1" });
  });
});
