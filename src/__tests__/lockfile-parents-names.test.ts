/**
 * Parent edges name the real package, not an alias or a tarball key.
 *
 * #27 fixed two naming defects in the package readers (yarn npm aliases read
 * as package names; pnpm 5 entries keyed by a tarball URL dropped). The
 * fix-path parent reader (`lockfile-parents.ts`) parsed the same lockfiles
 * with its own code and kept both defects: an aliased parent was reported
 * under its alias, an aliased dependency edge was never matched, and a
 * tarball-keyed pnpm entry was dropped as parent and as child. A wrong or
 * missing parent decides "a lockfile refresh is enough" vs "the parent must
 * move" (AD-055). The fixtures are excerpts of the 4DA conformance corpus
 * (hono's benchmarks/routers yarn.lock, trpc's pnpm 5.4 lockfile); the last
 * block reads the fetched corpus itself when it is present.
 */

