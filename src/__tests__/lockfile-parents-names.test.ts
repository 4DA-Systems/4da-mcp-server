const edge = (parent: string, parentVersion: string | null, range: string | null, local = false) => ({ parent, parentVersion, range, local });

describe("yarn berry: npm aliases in parent edges", () => {
  it("an aliased dependency edge names the parent, with the real package's range", () => {
    expect(yarnParents(BERRY, "string-width", "4.2.3")).toEqual([
      edge("@isaacs/cliui", "8.0.2", "^4.2.0"),
      edge("wrap-ansi", "7.0.0", "^4.1.0"),
    ]);
  });

  it("a parent installed under an alias is named by the package it resolves to", () => {
    expect(yarnParents(BERRY, "strip-ansi", "6.0.1")).toEqual([
      edge("@isaacs/cliui", "8.0.2", "^6.0.1"),
      edge("string-width", "4.2.3", "^6.0.1"),
      edge("wrap-ansi", "7.0.0", "^6.0.0"),
    ]);
  });

  it("the alias itself is not a package: it has no parents", () => {
    expect(yarnParents(BERRY, "string-width-cjs", "4.2.3")).toEqual([]);
  });
});

describe("yarn v1: npm aliases in parent edges", () => {
  it("an aliased dependency edge names the parent, with the real package's range", () => {
    expect(yarnParents(V1, "string-width", "4.2.3")).toEqual([edge("@isaacs/cliui", "8.0.2", "^4.2.0"), edge("wrap-ansi", "7.0.0", "^4.1.0")]);
  });

  it("a parent installed under an alias is named by the package it resolves to", () => {
    expect(yarnParents(V1, "strip-ansi", "6.0.1")).toEqual([
      edge("@isaacs/cliui", "8.0.2", "^6.0.1"),
      edge("string-width", "4.2.3", "^6.0.1"),
      edge("wrap-ansi", "7.0.0", "^6.0.0"),
    ]);
  });
});

describe("pnpm 5: entries keyed by a tarball URL", () => {
  it("a tarball-keyed entry is a parent, named by its name:/version: fields", () => {
    expect(pnpmParents(PNPM5, "prisma", "4.7.1")).toEqual([
      edge("examples/.interop/next-prisma-starter", null, null, true),
      edge("@prisma/client", "4.7.1", null),
    ]);
  });

  it("a dependency that points at a tarball-keyed entry is an edge to that package", () => {
    expect(pnpmParents(PNPM5, "@prisma/client", "4.7.1")).toEqual([edge("examples/.interop/next-prisma-starter", null, null, true)]);
  });

  it("ordinary pnpm 5 edges are unchanged", () => {
    expect(pnpmParents(PNPM5, "@prisma/engines", "4.7.1")).toEqual([edge("prisma", "4.7.1", null)]);
  });
});

describe("pnpm aliases: a dependency value that names another package", () => {
  it("v5 `alias: /real/1.2.3` and v6 `alias: /real@1.2.3` are edges to the real package", () => {
    const v5 = [
      "lockfileVersion: 5.4", "", "packages:", "",
      "  /string-width/4.2.3:", "    resolution: {integrity: sha512-x}", "",
      "  /@isaacs/cliui/8.0.2:", "    resolution: {integrity: sha512-x}", "    dependencies:",
      "      string-width: 5.1.2", "      string-width-cjs: /string-width/4.2.3", "",
    ].join("\n");
    expect(pnpmParents(v5, "string-width", "4.2.3")).toEqual([edge("@isaacs/cliui", "8.0.2", null)]);
    expect(pnpmParents(v5, "string-width-cjs", "4.2.3")).toEqual([]);
    const v6 = [
      "lockfileVersion: '6.0'", "", "packages:", "",
      "  /string-width@4.2.3:", "    resolution: {integrity: sha512-x}", "",
      "  /@isaacs/cliui@8.0.2:", "    resolution: {integrity: sha512-x}", "    dependencies:",
      "      string-width: 5.1.2", "      string-width-cjs: /string-width@4.2.3", "",
    ].join("\n");
    expect(pnpmParents(v6, "string-width", "4.2.3")).toEqual([edge("@isaacs/cliui", "8.0.2", null)]);
  });
});

// ---------------------------------------------------------------------------
// The corpus itself, when fetched (`node scripts/fetch-conformance.mjs`).
// ---------------------------------------------------------------------------

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const cases = path.resolve(process.env.FOURDA_CONFORMANCE_DIR ?? path.join(repoRoot, "conformance", "corpus"), "cases");
const routers = path.join(cases, "js-hono-bun", "benchmarks", "routers", "yarn.lock");
const trpc = path.join(cases, "js-trpc-pnpm5", "pnpm-lock.yaml");

describe.skipIf(!fs.existsSync(routers) || !fs.existsSync(trpc))("parent edges on the conformance corpus", () => {
  it("hono routers yarn.lock: no parent is an alias, and @isaacs/cliui pulls string-width 4.2.3", () => {
    const parents = readLockfileParents(routers, "string-width", "4.2.3");
    expect(parents?.format).toBe("yarn-berry");
    expect(parents?.edges.map((e) => e.parent)).toContain("@isaacs/cliui");
    for (const name of ["strip-ansi", "string-width", "ansi-regex", "ansi-styles"]) {
      const content = fs.readFileSync(routers, "utf-8");
      const versions = new Set([...content.matchAll(new RegExp(`^"${name}@npm:[^\\n]*\\n  version: (\\S+)`, "gm"))].map((m) => m[1]));
      for (const v of versions) {
        for (const e of readLockfileParents(routers, name, v)?.edges ?? []) expect(e.parent).not.toMatch(/-cjs$/);
      }
    }
  });

  it("trpc pnpm-lock.yaml: the four tarball-keyed @prisma/client copies are parents of prisma 4.7.1, and importers depend on them", () => {
    const prisma = readLockfileParents(trpc, "prisma", "4.7.1");
    expect(prisma?.edges.filter((e) => e.parent === "@prisma/client")).toEqual([edge("@prisma/client", "4.7.1", null)]);
    const client = readLockfileParents(trpc, "@prisma/client", "4.7.1");
    expect(client?.edges.map((e) => e.parent).sort()).toEqual([
      "examples/.interop/next-prisma-starter",
      "examples/next-prisma-starter",
      "examples/next-prisma-todomvc",
      "examples/next-prisma-websockets-starter",
    ]);
    expect(client?.edges.every((e) => e.local)).toBe(true);
  });
});
