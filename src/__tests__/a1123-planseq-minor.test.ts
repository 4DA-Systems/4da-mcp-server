/**
 * Smaller ways a plan step failed when run: an exact npm override forced the package's other copies
 * down (http-server's cross-spawn 7.0.6 to 6.0.6), and `yarn upgrade <name>` on Yarn classic moved
 * only the yarn.lock entry its declared range keys (zustand's @babel/core). The repeated Cargo
 * `--precise` (exit 101) is run once by run_order (a1123-planseq-run-order.test.ts).
 */

import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { adv, createHarness, fixedIn, type Harness } from "./helpers/a1119-planner-harness.js";

let h: Harness;
beforeEach(() => {
  h = createHarness();
});
afterEach(() => h.dispose());

describe("an override when the lockfile holds other versions of the package", () => {
  function project(others: boolean) {
    h.ADVISORIES = { child: [adv("GHSA-cccc-0003", "child", fixedIn("1.0.2"))] };
    h.NPM = {
      par: { latest: "1.0.0", versions: { "1.0.0": { dependencies: { child: "1.0.0" } } } },
      other: { latest: "1.0.0", versions: { "1.0.0": { dependencies: { child: "^2.0.0" } } } },
      child: { latest: "2.1.0", versions: { "1.0.0": {}, "1.0.2": {}, "2.1.0": {} } },
    };
    h.npmProject(others ? { par: "1.0.0", other: "1.0.0" } : { par: "1.0.0" }, {}, {
      par: { version: "1.0.0", dependencies: { child: "1.0.0" } },
      child: { version: "1.0.0" },
      ...(others ? { other: { version: "1.0.0", dependencies: { child: "^2.0.0" } }, "other/node_modules/child": { version: "2.1.0" } } : {}),
    });
  }

  it("is scoped to the vulnerable copy's parents, and says which copies a bare entry would force", async () => {
    project(true);
    const { step } = await h.plan();
    const row = step("child", "1.0.0");
    expect(row.action).toBe("override_or_replace");
    const why = row.reasons.join(" ");
    expect(why).toContain('npm: add "overrides": { "par": { "child": "1.0.2" } } to package.json (npm 8.3+), then npm install (scoped to par: a bare "child" entry would also force child 2.1.0, which this lockfile holds too, to 1.0.2)');
    expect(why).not.toContain('"overrides": { "child": "1.0.2" }');
  });

  it("stays the plain entry when the copy is the only version installed", async () => {
    project(false);
    const { step } = await h.plan();
    expect(step("child", "1.0.0").reasons.join(" ")).toContain('npm: add "overrides": { "child": "1.0.2" } to package.json (npm 8.3+), then npm install');
  });
});

describe("Yarn classic: a declared package locked under several entries at the same version", () => {
  const entry = (keys: string) => `${keys}:\n  version "7.19.6"\n  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.19.6.tgz#a"\n  integrity sha512-core\n`;
  function project(twoEntries: boolean) {
    h.ADVISORIES = { "@babel/core": [adv("GHSA-4x5r-pxfx-6jf8", "@babel/core", fixedIn("7.20.0"))] };
    h.NPM = {
      "@babel/core": { latest: "7.20.0", versions: { "7.19.6": {}, "7.20.0": {} } },
      "jest-thing": { latest: "1.0.0", versions: { "1.0.0": { dependencies: { "@babel/core": "^7.11.6" } } } },
    };
    h.write("package.json", JSON.stringify({ name: "x", version: "1.0.0", dependencies: { "@babel/core": "^7.19.6", ...(twoEntries ? { "jest-thing": "1.0.0" } : {}) } }));
    const lock = [
      "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n",
      twoEntries ? entry('"@babel/core@^7.11.6", "@babel/core@^7.12.3"') + "\n" : "",
      entry('"@babel/core@^7.19.6"'),
      twoEntries
        ? '\njest-thing@1.0.0:\n  version "1.0.0"\n  resolved "https://registry.yarnpkg.com/jest-thing/-/jest-thing-1.0.0.tgz#b"\n  integrity sha512-jest\n  dependencies:\n    "@babel/core" "^7.11.6"\n'
        : "",
    ].join("");
    h.write("yarn.lock", lock);
  }

  it("gives the hand steps that move every entry, not `yarn upgrade`, and run_order leaves it out", async () => {
    project(true);
    const { result, step } = await h.plan();
    const row = step("@babel/core");
    expect(row.action).toBe("upgrade_direct");
    expect(row.upgradeCommands).toBeUndefined();
    expect(row.upgradeInstructions).toEqual([{ dir: ".", instruction: 'delete every yarn.lock entry that resolves to @babel/core (keys "@babel/core@…" and alias keys "…@npm:@babel/core@…"), then run yarn install' }]);
    expect(row.reasons.join(" ")).toMatch(/yarn\.lock holds @babel\/core 7\.19\.6 under 2 entries \("@babel\/core@\^7\.11\.6, @babel\/core@\^7\.12\.3"; "@babel\/core@\^7\.19\.6"\)/);
    expect(row.commands).toEqual([]);
    expect(result.run_order.map((s: { run: string }) => s.run)).not.toContain("yarn upgrade @babel/core");
    expect(result.run_order_note).toMatch(/not fixed by commands alone .*: @babel\/core 7\.19\.6/);
  });

  it("keeps `yarn upgrade` when one entry holds the version", async () => {
    project(false);
    const { step } = await h.plan();
    expect(step("@babel/core").commands).toEqual([{ dir: ".", run: "yarn upgrade @babel/core" }]);
  });
});
