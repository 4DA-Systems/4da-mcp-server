/**
 * An exact Yarn classic resolution forces the release a refresh resolves to (the newest clean
 * release the parents admit, which the row's reason states), not the smallest fix. formik 2.2.9,
 * replayed 2026-11-26 (scripts off): the plan's resolutions sat at the smallest fix
 * (@babel/helpers 7.26.10, json5 2.2.2); step 39, `yarn workspace formik add "lodash@^4.18.1"`,
 * raised them to 7.29.15 and 2.2.3 (Yarn 1 ignores the root's resolutions there), and step 77,
 * the root's `yarn upgrade husky`, forced them back down: a lowering of what an earlier step set.
 */

import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { adv, createHarness, fixedIn, type Harness } from "./helpers/a1119-planner-harness.js";

let h: Harness;
beforeEach(() => {
  h = createHarness();
});
afterEach(() => h.dispose());

const lock = [
  "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
  "# yarn lockfile v1",
  "",
  "",
  "loader@1.0.0:",
  '  version "1.0.0"',
  '  resolved "https://registry.yarnpkg.com/loader/-/loader-1.0.0.tgz"',
  "  integrity sha512-AAAA",
  "  dependencies:",
  '    json5 "^2.1.1"',
  "",
  "json5@^2.1.1:",
  '  version "2.1.1"',
  '  resolved "https://registry.yarnpkg.com/json5/-/json5-2.1.1.tgz"',
  "  integrity sha512-AAAA",
  "",
].join("\n");

describe("Yarn classic exact resolution", () => {
  it("forces the release a refresh resolves to, not the smallest fix (formik json5, @babel/helpers)", async () => {
    h.ADVISORIES = { json5: [adv("GHSA-9c47-m6qq-7p4h", "json5", fixedIn("2.2.2"))] };
    h.NPM = {
      json5: { latest: "2.2.3", versions: { "2.1.1": {}, "2.2.2": {}, "2.2.3": {} } },
      loader: { latest: "1.0.0", versions: { "1.0.0": { dependencies: { json5: "^2.1.1" } } } },
    };
    h.write("package.json", JSON.stringify({ name: "formik-root", version: "1.0.0", dependencies: { loader: "1.0.0" } }));
    h.write("yarn.lock", lock);
    const { step } = await h.plan();
    const row = step("json5");
    expect(row.reasons.join(" | ")).toContain("(a refresh resolves it to 2.2.3)");
    expect(row.commands).toEqual([
      { dir: ".", run: 'npm pkg set "resolutions.json5=2.2.3"' },
      { dir: ".", run: "yarn install" },
    ]);
    expect(row.reasons.join(" | ")).toContain("at or below 2.2.3 (the release a refresh resolves it to; 2.2.2 is the smallest fix), so an exact resolution moves them all there");
  });
});
