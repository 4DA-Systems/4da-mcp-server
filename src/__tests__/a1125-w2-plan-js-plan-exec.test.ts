/**
 * The plan-execution harness (bench/plan-exec) runs the planner's own Yarn workspace command and
 * picks the Yarn flavour from the project, not from the step's directory. Audit 2026-11-25, Track B:
 * it refused every `yarn workspace <member> add` step (formik 3, redux-toolkit 12), and once allowed,
 * gave a Berry member's step Yarn 1's flags (the member's directory has no yarn.lock), which failed
 * with a Usage Error. A project can also carry its own floors (`projects.<id>` in thresholds.json).
 */
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { gateFindings, predictionCheck, prepareCommand, tokenize, totals, yarnFlavorFor, type ProjectResult } from "../../bench/plan-exec/lib.mjs";

const dirs: string[] = [];
afterEach(() => {
  for (const d of dirs.splice(0)) fs.rmSync(d, { recursive: true, force: true });
});
const tmp = () => {
  const d = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "plan-exec-w2-")));
  dirs.push(d);
  return d;
};

describe("Yarn workspace steps", () => {
  it("runs `yarn workspace <member> add <spec>` with each flavour's flags", () => {
    const parts = tokenize('yarn workspace @rtk-query/graphql-request-base-query add "graphql@^16.8.1" --dev');
    expect(parts).toEqual({ parts: [["yarn", "workspace", "@rtk-query/graphql-request-base-query", "add", "graphql@^16.8.1", "--dev"]] });
    const argv = (parts as { parts: string[][] }).parts[0];
    expect(prepareCommand(argv, { yarnFlavor: "berry" })).toMatchObject({ argv: [...argv, "--mode", "update-lockfile"], env: { YARN_ENABLE_SCRIPTS: "false" } });
    expect(prepareCommand(argv, { yarnFlavor: "classic" })).toMatchObject({ argv: [...argv, "--ignore-scripts", "--ignore-engines", "--non-interactive"] });
  });

  it("refuses any other workspace subcommand, which can run a member's own scripts", () => {
    for (const argv of [["yarn", "workspace", "web", "run", "build"], ["yarn", "workspace", "web", "exec", "x"], ["yarn", "workspace", "web"], ["yarn", "workspace", "web", "add"]]) {
      expect(prepareCommand(argv, { yarnFlavor: "berry" }), argv.join(" ")).toHaveProperty("refused");
    }
  });

  it("takes the flavour from the nearest yarn.lock at or above the step's directory, inside the copy", () => {
    const copy = tmp();
    fs.mkdirSync(path.join(copy, "packages", "gql"), { recursive: true });
    fs.writeFileSync(path.join(copy, "yarn.lock"), '# This file is generated by running "yarn install" inside your project.\n\n__metadata:\n  version: 6\n');
    expect(yarnFlavorFor(copy, path.join(copy, "packages", "gql"))).toBe("berry");
    fs.mkdirSync(path.join(copy, "website"));
    fs.writeFileSync(path.join(copy, "website", "yarn.lock"), "# yarn lockfile v1\n");
    expect(yarnFlavorFor(copy, path.join(copy, "website"))).toBe("classic");
    // Never above the copy: a yarn.lock in the folder that holds the copy is not the project's.
    const outer = tmp();
    fs.writeFileSync(path.join(outer, "yarn.lock"), "__metadata:\n  version: 6\n");
    fs.mkdirSync(path.join(outer, "copy", "sub"), { recursive: true });
    expect(yarnFlavorFor(path.join(outer, "copy"), path.join(outer, "copy", "sub"))).toBe("classic");
  });
});

describe("a step that falls short of its fix", () => {
  it("counts a planned copy that moved to a release still carrying its advisory as planned but remained, not as a new copy (crewAI cryptography)", () => {
    const r = (pkg: string, version: string, id: string) => ({ ecosystem: "PyPI", package: pkg, current_version: version, vuln_id: id });
    const got = predictionCheck({
      beforeRows: [r("cryptography", "43.0.3", "GHSA-old-1"), r("cryptography", "43.0.3", "GHSA-old-2")],
      afterRows: [r("cryptography", "45.0.7", "GHSA-old-2"), r("cryptography", "45.0.7", "GHSA-new-1"), r("pillow", "11.0.0", "GHSA-p")],
      steps: [{ n: 1, fixes: ["PyPI:cryptography"], rows: [{ package: "cryptography", ecosystem: "PyPI", currentVersion: "43.0.3", targetVersion: "50.0.0" }], actions: [{ type: "run" as const, dir: ".", run: "uv lock" }] }],
    });
    expect(got.planned_but_remained).toEqual(["PyPI|cryptography|43.0.3 -> 45.0.7"]);
    expect(got.new_vulnerable_copies).toBe(1);
  });
});

describe("per-project floors", () => {
  const project = (id: string, before: number, after: number, failed = 0): ProjectResult => ({
    id,
    order_source: "run_order",
    counts: { steps: 10, steps_run: 10, steps_failed: failed, steps_refused: 0, steps_without_effect: 0, steps_lowering: 0, steps_lowering_earlier: 0 },
    advisories: { before, after },
    prediction: { vulnerable_copies_before: 10, predicted_remaining: 1, remaining: 1, vulnerable_copies_after: 1, planned_but_remained: [] },
  });
  it("a project below its own floor fails the gate even when the corpus total passes", () => {
    const thresholds = { min_net_cleared_ratio: 0.5, projects: { formik: { min_net_cleared_ratio: 0.62, max_failed_steps: 0 } } };
    const ok = [project("a", 1000, 10), project("formik", 400, 150)];
    expect(gateFindings(totals(ok), thresholds, ok)).toEqual([]);
    const low = [project("a", 1000, 10), project("formik", 400, 160, 1)];
    expect(gateFindings(totals(low), thresholds, low)).toEqual([
      "formik: 1 step(s) failed (allowed there: 0)",
      "formik: advisories 400 -> 160: 0.6 cleared, below its floor 0.62",
    ]);
  });
});

describe("groups", () => {
  const project = (id: string, before: number, after: number, lowering = 0): ProjectResult => ({
    id,
    order_source: "run_order",
    counts: { steps: 10, steps_run: 10, steps_failed: 0, steps_refused: 0, steps_without_effect: 0, steps_lowering: lowering, steps_lowering_earlier: 0 },
    advisories: { before, after },
    prediction: { vulnerable_copies_before: 10, predicted_remaining: 1, remaining: 1, vulnerable_copies_after: 1, planned_but_remained: [] },
  });
  it("holds a group of projects to its own numbers inside a larger corpus", () => {
    const thresholds = { min_net_cleared_ratio: 0.4, groups: { original: { ids: ["a", "b"], min_net_cleared_ratio: 0.77, max_lowering_steps: 1 } } };
    const ps = [project("a", 100, 20, 1), project("b", 100, 30), project("c", 1000, 600)];
    expect(gateFindings(totals(ps), thresholds, ps)).toEqual(["original: advisories 200 -> 50: 0.75 cleared, below the group's 0.77"]);
  });
});

describe("a group's two copy counts together", () => {
  it("fails when their sum passes max_planned_and_new_copies even though each is inside its own cap", () => {
    const p = (id: string, pbr: number, newc: number): ProjectResult => ({
      id,
      order_source: "run_order",
      counts: { steps: 1, steps_run: 1, steps_failed: 0, steps_refused: 0, steps_without_effect: 0, steps_lowering: 0, steps_lowering_earlier: 0 },
      advisories: { before: 10, after: 1 },
      prediction: { vulnerable_copies_before: 1, predicted_remaining: 0, remaining: 0, vulnerable_copies_after: 0, planned_but_remained: Array.from({ length: pbr }, (_, i) => `npm|x|${i}`), new_vulnerable_copies: newc },
    });
    const thresholds = { groups: { original: { ids: ["a"], max_planned_but_remained: 28, max_new_vulnerable_copies: 22, max_planned_and_new_copies: 50 } } };
    const ps = [p("a", 28, 22), p("b", 0, 0)];
    expect(gateFindings(totals(ps), thresholds, ps)).toEqual([]);
    const over = [p("a", 28, 22), p("b", 0, 0)];
    over[0].prediction.new_vulnerable_copies = 23;
    expect(gateFindings(totals(over), thresholds, over)).toEqual([
      "original: 23 vulnerable copies the run brought in that were not there before (allowed in the group: 22)",
      "original: 51 vulnerable copies a step ran for that stayed, or the run brought in, together (allowed in the group: 50)",
    ]);
  });
});
