/**
 * An exact Yarn classic resolution (`npm pkg set "resolutions.<name>=<target>"`, then `yarn install`)
 * forces every copy of the name in that yarn.lock to the target. Audit 2026-11-25, Track B, formik
 * 2.2.9: one minimatch row named the resolution for two lockfiles, the root and website/. Its own
 * order chained them (root set, root install, website set, website install), so website's set ran
 * after the root's install, which the script runs last: after website's `yarn upgrade` steps, one of
 * which had brought minimatch 3.1.5 in, and website's `yarn install` then lowered it to 3.1.4.
 *
 * Commands of one row that act on different lockfiles are not ordered against each other, and an
 * override or resolution runs before the version-setting steps on its own lockfile: an install then
 * never takes a copy past the forced release only for a later step to force it down again.
 */

import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { adv, createHarness, fixedIn, type Harness } from "./helpers/a1119-planner-harness.js";

let h: Harness;
beforeEach(() => {
  h = createHarness();
});
afterEach(() => h.dispose());

type Step = { n: number; dir: string; run: string; fixes: string[] };

const classicLock = (blocks: Array<{ keys: string[]; version: string; deps?: Record<string, string> }>) =>
  [
    "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
    "# yarn lockfile v1",
    "",
    "",
    ...blocks.flatMap((b) => {
      const name = b.keys[0].slice(0, b.keys[0].lastIndexOf("@"));
      return [
        `${b.keys.join(", ")}:`,
        `  version "${b.version}"`,
        `  resolved "https://registry.yarnpkg.com/${name}/-/${name}-${b.version}.tgz"`,
        "  integrity sha512-AAAA",
        ...(b.deps ? ["  dependencies:", ...Object.entries(b.deps).map(([d, r]) => `    ${d} "${r}"`)] : []),
        "",
      ];
    }),
  ].join("\n");

describe("Yarn classic: an exact resolution and the upgrades on its lockfile", () => {
  it("each lockfile's resolution runs before that lockfile's upgrades, not after the other lockfile's install (formik minimatch)", async () => {
    h.ADVISORIES = {
      minimatch: [adv("GHSA-f8q6-p94x-37v3", "minimatch", fixedIn("3.1.4"))],
      next: [adv("GHSA-fr5h-rqp8-mj6g", "next", fixedIn("16.0.0"), "npm", "CRITICAL")],
    };
    h.NPM = {
      minimatch: { latest: "3.1.5", versions: { "3.0.4": {}, "3.1.4": {}, "3.1.5": {} } },
      glob: { latest: "7.2.0", versions: { "7.2.0": { dependencies: { minimatch: "^3.0.4" } } } },
      next: { latest: "16.0.0", versions: { "10.0.5": {}, "16.0.0": { dependencies: { minimatch: "^3.1.5" } } } },
    };
    const lock = (extra: Array<{ keys: string[]; version: string; deps?: Record<string, string> }> = []) =>
      classicLock([{ keys: ["glob@7.2.0"], version: "7.2.0", deps: { minimatch: "^3.0.4" } }, { keys: ["minimatch@^3.0.4"], version: "3.0.4" }, ...extra]);
    h.write("package.json", JSON.stringify({ name: "formik-root", version: "1.0.0", dependencies: { glob: "7.2.0" } }));
    h.write("yarn.lock", lock());
    h.write("website/package.json", JSON.stringify({ name: "website", version: "1.0.0", dependencies: { glob: "7.2.0", next: "10.0.5" } }));
    h.write("website/yarn.lock", lock([{ keys: ["next@10.0.5"], version: "10.0.5" }]));

    const { result, step } = await h.plan();
    const mm = step("minimatch");
    expect(mm.commands).toEqual([
      { dir: ".", run: 'npm pkg set "resolutions.minimatch=3.1.4"' },
      { dir: ".", run: "yarn install" },
      { dir: "website", run: 'npm pkg set "resolutions.minimatch=3.1.4"' },
      { dir: "website", run: "yarn install" },
    ]);
    const steps = result.run_order as Step[];
    const at = (dir: string, run: string) => steps.findIndex((s) => s.dir === dir && s.run === run);
    const websiteResolution = at("website", 'npm pkg set "resolutions.minimatch=3.1.4"');
    const websiteUpgrade = steps.findIndex((s) => s.dir === "website" && /^yarn upgrade next@16\.0\.0$/.test(s.run));
    expect(websiteResolution).toBeGreaterThanOrEqual(0);
    expect(websiteUpgrade).toBeGreaterThanOrEqual(0);
    expect(websiteResolution).toBeLessThan(websiteUpgrade);
    // Each lockfile's install still follows its own resolution.
    expect(at("website", "yarn install")).toBeGreaterThan(websiteResolution);
    expect(at(".", "yarn install")).toBeGreaterThan(at(".", 'npm pkg set "resolutions.minimatch=3.1.4"'));
  });
});
