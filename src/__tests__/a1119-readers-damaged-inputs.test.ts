/**
 * Damaged or out-of-date JavaScript inputs are reported, never read as
 * complete and never read as absent.
 *
 * A text lockfile has no closing bracket to miss, so one cut between two
 * entries parses cleanly. Two properties of every whole lockfile catch it:
 * each dependency the project's package.json declares has an entry, and (yarn)
 * each dependency an entry names has an entry. A package.json that is not
 * JSON, with no lockfile to read instead, is itself reported.
 */

import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import * as path from "node:path";
import Database from "better-sqlite3";
import { LiveIntelligence } from "../live/index.js";
import { resolveVersionSource } from "../live/lockfile-parsers.js";
import type { LockfileProblem } from "../live/lockfile-types.js";
import { scanProjectTree, treeResolutionGroups } from "../project-tree.js";
import { executeDependencyHealth } from "../tools/dependency-health.js";
import { executeUpgradePlanner } from "../tools/upgrade-planner.js";
import { npmAdvisory, removeProject, scanProject, stubOsv, tempProject, vulnerableCopies } from "./helpers/a1119-readers.js";

const y = (name: string, version: string) => `https://registry.yarnpkg.com/${name}/-/${name.split("/").pop()}-${version}.tgz#0123456789abcdef0123456789abcdef01234567`;
const v1Block = (header: string, name: string, version: string, deps: Record<string, string> = {}) =>
  `${header}:\n  version "${version}"\n  resolved "${y(name, version)}"\n  integrity sha512-AAAA\n${Object.keys(deps).length > 0 ? `  dependencies:\n${Object.entries(deps).map(([n, r]) => `    ${n} "${r}"\n`).join("")}` : ""}\n`;

const YARN_MANIFEST = {
  name: "fx",
  version: "1.0.0",
  private: true,
  dependencies: { debug: "2.6.9", express: "4.17.1", optimist: "0.6.1" },
  devDependencies: { mkdirp: "0.5.1" },
};
const YARN_HEADER = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n";
const YARN_BLOCKS = [
  v1Block("debug@2.6.9", "debug", "2.6.9", { ms: "2.0.0" }),
  v1Block("express@4.17.1", "express", "4.17.1", { debug: "2.6.9", qs: "6.7.0" }),
  v1Block("minimist@0.0.8", "minimist", "0.0.8"),
  v1Block("minimist@~0.0.1", "minimist", "0.0.10"),
  v1Block("mkdirp@0.5.1", "mkdirp", "0.5.1", { minimist: "0.0.8" }),
  v1Block("ms@2.0.0", "ms", "2.0.0"),
  v1Block("optimist@0.6.1", "optimist", "0.6.1", { minimist: "~0.0.1", wordwrap: "~0.0.2" }),
  v1Block("qs@6.7.0", "qs", "6.7.0"),
  v1Block("wordwrap@~0.0.2", "wordwrap", "0.0.3"),
];
const yarnLock = (blocks: string[]) => YARN_HEADER + blocks.join("");

const partial = (problems: LockfileProblem[] | undefined) => (problems ?? []).filter((p) => p.partial === true);

describe("damaged JavaScript inputs", () => {
  let dirs: string[];
  let priorOffline: string | undefined;
  const project = (files: Record<string, string>) => {
    const dir = tempProject(files);
    dirs.push(dir);
    return dir;
  };

  beforeEach(() => {
    dirs = [];
    priorOffline = process.env.FOURDA_OFFLINE;
    delete process.env.FOURDA_OFFLINE;
  });

  afterEach(() => {
    vi.unstubAllGlobals();
    if (priorOffline === undefined) delete process.env.FOURDA_OFFLINE;
    else process.env.FOURDA_OFFLINE = priorOffline;
    dirs.forEach(removeProject);
  });

  describe("yarn.lock cut between two entries", () => {
    it("is reported incomplete, naming the first declared dependency with no entry", () => {
      // Everything from ms on is gone: optimist, which package.json declares, has no entry.
      const dir = project({ "package.json": JSON.stringify(YARN_MANIFEST), "yarn.lock": yarnLock(YARN_BLOCKS.slice(0, 5)) });
      const read = resolveVersionSource(dir, "npm");
      expect(read.instances).toHaveLength(5);
      const problems = partial(read.problems);
      expect(problems).toHaveLength(1);
      expect(path.basename(problems[0].file)).toBe("yarn.lock");
      expect(problems[0].error).toMatch(/package\.json declares optimist \(dependencies\)/);
      expect(problems[0].error).toMatch(/no entry/);
      expect(problems[0].error).toMatch(/truncated, or older than package\.json/);
    });

    it("is reported when every declared dependency survives but an entry's own dependency does not", () => {
      // Cut after optimist: package.json's four dependencies all have entries; qs and wordwrap, which express and optimist need, do not.
      const dir = project({ "package.json": JSON.stringify(YARN_MANIFEST), "yarn.lock": yarnLock(YARN_BLOCKS.slice(0, 7)) });
      const problems = partial(resolveVersionSource(dir, "npm").problems);
      expect(problems).toHaveLength(1);
      expect(problems[0].error).toMatch(/2 packages named as dependencies have no entry \(qs, wordwrap\)/);
    });

    it("is not a clean result in the scan", async () => {
      stubOsv([]);
      const dir = project({ "package.json": JSON.stringify(YARN_MANIFEST), "yarn.lock": yarnLock(YARN_BLOCKS.slice(0, 5)) });
      const answer = await scanProject(dir);
      expect(answer.coverage).toMatchObject({ complete: false });
      expect(answer.coverage.partial_lockfiles).toEqual([expect.objectContaining({ path: "yarn.lock" })]);
      expect(answer.coverage.note).toMatch(/PARTIAL: 1 lockfile was NOT read to the end: yarn\.lock \(package\.json declares optimist/);
    });

    it("a whole lockfile raises nothing: aliases, git, linked and workspace dependencies included", () => {
      const manifest = {
        ...YARN_MANIFEST,
        workspaces: ["packages/*"],
        dependencies: { ...YARN_MANIFEST.dependencies, "my-ms": "npm:ms@2.0.0", "left-pad": "git+https://github.com/left-pad/left-pad.git#2fca615", local: "link:./vendor/local", "fx-api": "1.0.0" },
        peerDependencies: { react: ">=17" },
      };
      const extra = [
        '"left-pad@git+https://github.com/left-pad/left-pad.git#2fca615":\n  version "1.3.0"\n  resolved "git+https://github.com/left-pad/left-pad.git#2fca6157fcca165438d5fb17cbb7dfa4d5a4fd76"\n\n',
        v1Block('"my-ms@npm:ms@2.0.0"', "ms", "2.0.0"),
      ];
      const dir = project({
        "package.json": JSON.stringify(manifest),
        "packages/api/package.json": JSON.stringify({ name: "fx-api", version: "1.0.0" }),
        "yarn.lock": yarnLock([...YARN_BLOCKS, ...extra]),
      });
      expect(resolveVersionSource(dir, "npm").problems ?? []).toEqual([]);
    });

    it("berry: a missing declared dependency is reported, a whole lockfile is not", () => {
      const berryBlock = (name: string, range: string, version: string, deps: Record<string, string> = {}) =>
        `"${name}@npm:${range}":\n  version: ${version}\n  resolution: "${name}@npm:${version}"\n${Object.keys(deps).length > 0 ? `  dependencies:\n${Object.entries(deps).map(([n, r]) => `    ${n}: "npm:${r}"\n`).join("")}` : ""}  checksum: 10c0/0123456789abcdef\n  languageName: node\n  linkType: hard\n\n`;
      const head = '# This file is generated by running "yarn install" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10c0\n\n';
      const workspace = '"fx@workspace:.":\n  version: 0.0.0-use.local\n  resolution: "fx@workspace:."\n  dependencies:\n    debug: "npm:2.6.9"\n    mkdirp: "npm:0.5.1"\n  languageName: unknown\n  linkType: soft\n\n';
      const manifest = JSON.stringify({ name: "fx", dependencies: { debug: "2.6.9" }, devDependencies: { mkdirp: "0.5.1" } });
      const blocks = [berryBlock("debug", "2.6.9", "2.6.9", { ms: "2.0.0" }), workspace, berryBlock("minimist", "0.0.8", "0.0.8"), berryBlock("mkdirp", "0.5.1", "0.5.1", { minimist: "0.0.8" }), berryBlock("ms", "2.0.0", "2.0.0")];
      expect(resolveVersionSource(project({ "package.json": manifest, "yarn.lock": head + blocks.join("") }), "npm").problems ?? []).toEqual([]);
      const cut = partial(resolveVersionSource(project({ "package.json": manifest, "yarn.lock": head + blocks.slice(0, 3).join("") }), "npm").problems);
      expect(cut).toHaveLength(1);
      expect(cut[0].error).toMatch(/package\.json declares mkdirp \(devDependencies\)/);
    });
  });

  describe("pnpm-lock.yaml and bun.lock against package.json", () => {
    const pnpmLock = (deps: string[]) =>
      [
        "lockfileVersion: '9.0'",
        "",
        "importers:",
        "",
        "  .:",
        "    dependencies:",
        ...deps.flatMap((d) => [`      ${d}:`, "        specifier: 1.0.0", "        version: 1.0.0"]),
        "",
        "packages:",
        "",
        ...deps.flatMap((d) => [`  ${d}@1.0.0:`, "    resolution: {integrity: sha512-AAAA}", ""]),
        "snapshots:",
        "",
        ...deps.flatMap((d) => [`  ${d}@1.0.0: {}`, ""]),
      ].join("\n");

    it("pnpm: a dependency package.json declares that the importer does not hold is reported", () => {
      // A workspace link is not owed an entry: `excludeLinksFromLockfile` leaves links out of the importer.
      const manifest = JSON.stringify({ name: "x", dependencies: { alpha: "1.0.0", beta: "1.0.0", gamma: "1.0.0", link: "workspace:*" } });
      expect(resolveVersionSource(project({ "package.json": manifest, "pnpm-lock.yaml": pnpmLock(["alpha", "beta", "gamma"]) }), "npm").problems ?? []).toEqual([]);
      const stale = partial(resolveVersionSource(project({ "package.json": manifest, "pnpm-lock.yaml": pnpmLock(["alpha"]) }), "npm").problems);
      expect(stale).toHaveLength(1);
      expect(stale[0].error).toMatch(/package\.json declares beta \(dependencies\) and 1 more/);
    });

    it("pnpm: a lockfile cut before its packages, beside a package.json that declares dependencies, is not read as absent", () => {
      const manifest = JSON.stringify({ name: "x", dependencies: { alpha: "1.0.0" } });
      const dir = project({ "package.json": manifest, "pnpm-lock.yaml": "lockfileVersion: '9.0'\n\nimporters:\n\n  .:\n    dependencies:\n" });
      const read = resolveVersionSource(dir, "npm");
      expect(read.problems).toHaveLength(1);
      expect(path.basename(read.problems![0].file)).toBe("pnpm-lock.yaml");
      expect(read.problems![0].error).toMatch(/holds no package.*package\.json declares alpha/);
    });

    const bunLock = (deps: string[]) =>
      `{\n  "lockfileVersion": 1,\n  "workspaces": {\n    "": {\n      "name": "x",\n      "dependencies": {\n${deps.map((d) => `        "${d}": "1.0.0",\n`).join("")}      },\n    },\n  },\n  "packages": {\n${deps.map((d) => `    "${d}": ["${d}@1.0.0", "", {}, "sha512-AAAA=="],\n\n`).join("")}  }\n}\n`;

    it("bun: a dependency package.json declares with no entry is reported", () => {
      const manifest = JSON.stringify({ name: "x", dependencies: { alpha: "1.0.0", beta: "1.0.0" } });
      expect(resolveVersionSource(project({ "package.json": manifest, "bun.lock": bunLock(["alpha", "beta"]) }), "npm").problems ?? []).toEqual([]);
      const stale = partial(resolveVersionSource(project({ "package.json": manifest, "bun.lock": bunLock(["alpha"]) }), "npm").problems);
      expect(stale).toHaveLength(1);
      expect(stale[0].error).toMatch(/package\.json declares beta \(dependencies\)/);
    });

    it("bun: a short lockfile cut mid-file is unreadable, not a project with no lockfile", () => {
      const manifest = JSON.stringify({ name: "x", dependencies: { alpha: "1.0.0", beta: "1.0.0" } });
      const whole = bunLock(["alpha", "beta"]);
      const dir = project({ "package.json": manifest, "bun.lock": whole.slice(0, Math.floor(whole.length * 0.8)) });
      const read = resolveVersionSource(dir, "npm");
      const named = (read.problems ?? []).filter((p) => path.basename(p.file) === "bun.lock");
      expect(named).toHaveLength(1);
      expect(named[0].error).toMatch(/invalid JSON/);
    });
  });

  describe("a package.json that is not JSON, with no lockfile", () => {
    const BROKEN = '{ "name": "x", "dependencies": { "lodash": "4.17.15" ';
    const plan = async (dir: string) => {
      const live = new LiveIntelligence(new Database(":memory:"));
      const { entries, discovery } = scanProjectTree(dir);
      live.initFromProjectTree(dir, treeResolutionGroups(entries), discovery);
      return (await executeUpgradePlanner(null as never, { project_path: dir } as never, live)) as Record<string, any>;
    };

    it("is reported unreadable by the resolution", () => {
      const dir = project({ "package.json": BROKEN });
      const read = resolveVersionSource(dir, "npm");
      expect(read.instances).toEqual([]);
      expect(read.problems).toHaveLength(1);
      expect(path.basename(read.problems![0].file)).toBe("package.json");
      expect(read.problems![0].error).toMatch(/not valid JSON/);
    });

    it("the scan says nothing was checked and names the manifest, with no clean count", async () => {
      stubOsv([]);
      const answer = await scanProject(project({ "package.json": BROKEN }));
      const text = JSON.stringify(answer);
      expect(text).toMatch(/UNREADABLE/);
      expect(text).toMatch(/package\.json/);
      expect(text).not.toMatch(/No manifest or lockfile of a supported ecosystem was found/);
      expect(text).not.toMatch(/Found package\.json but no lock file/);
      expect(answer.coverage).toMatchObject({ complete: false, unreadable_lockfiles: [expect.objectContaining({ path: "package.json" })] });
      expect(answer.note).toMatch(/^Nothing was checked\. UNREADABLE/);
    });

    it("the planner does not claim vulnerability data", async () => {
      stubOsv([]);
      const answer = await plan(project({ "package.json": BROKEN }));
      expect(answer.vulnerabilityDataAvailable).toBe(false);
      expect(answer.summary).toMatch(/UNREADABLE.*package\.json/);
    });

    it("dependency_health says nothing was checked and names the manifest", async () => {
      stubOsv([]);
      const dir = project({ "package.json": BROKEN });
      const live = new LiveIntelligence(new Database(":memory:"));
      const { entries, discovery } = scanProjectTree(dir);
      live.initFromProjectTree(dir, treeResolutionGroups(entries), discovery);
      const answer = (await executeDependencyHealth(null, {}, live)) as Record<string, any>;
      expect(answer.healthScore).toBeNull();
      expect(answer.summary).toMatch(/^Nothing was checked.*UNREADABLE.*package\.json/);
    });

    it("beside a good requirements.txt the npm side is still named", async () => {
      stubOsv([npmAdvisory("GHSA-35jh-r3h4-6jhm", "lodash", "4.17.21")]);
      const dir = project({ "package.json": BROKEN, "requirements.txt": "requests==2.31.0\n" });
      const answer = await scanProject(dir);
      expect(answer.total_dependencies_scanned).toBe(1);
      expect(vulnerableCopies(answer)).toEqual([]);
      expect(answer.coverage).toMatchObject({ complete: false, unreadable_lockfiles: [expect.objectContaining({ path: "package.json" })] });
      expect(answer.coverage.note).toMatch(/UNREADABLE: .*package\.json/);
      expect((await plan(dir)).summary).toMatch(/UNREADABLE.*package\.json/);
    });

    it("a package.json that parses is read as before", () => {
      const dir = project({ "package.json": JSON.stringify({ name: "x", dependencies: { lodash: "4.17.15" } }) });
      const read = resolveVersionSource(dir, "npm");
      expect(read.problems ?? []).toEqual([]);
      expect(read.kind).toBe("declared_ranges");
    });
  });
});
