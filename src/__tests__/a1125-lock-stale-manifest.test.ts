/**
 * Audit 2026-11-25, track A (F1, F3, F4, F5, F6): a lockfile is held to the manifest beside it and
 * to itself, for the formats that were not.
 *
 * - F1: a Gemfile.lock, Pipfile.lock, pdm.lock, poetry.lock or composer.lock older than its manifest
 *   (the manifest declares a package the lockfile has no entry for) read as complete. npm and uv
 *   already said PARTIAL; these five now do too. A requirement a lockfile may legitimately omit (a
 *   platform package, a conditional gem, a marker, a path or git source, a virtual package another
 *   entry provides, the project's own extra) never makes a good lockfile partial, and a manifest
 *   that cannot be read is said as not compared, never as damage.
 * - F3: a Gemfile.lock GEM section with a private remote is private as a whole, whichever remote
 *   comes first (which remote served which gem is not recorded).
 * - F4: a package another entry depends on and that has no entry of its own is damage.
 * - F5: GIT gems and composer branch checkouts (`dev-main`) are listed as not checkable.
 * - F6: a pdm.lock git package reads as poetry's does: not checkable, never an index release.
 */
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { resolveVersionSource } from "../live/lockfile-parsers.js";
import type { OsvEcosystem } from "../live/types.js";

let dir: string;
beforeEach(() => {
  dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "4da-a1125-lock-")));
});
afterEach(() => {
  try {
    fs.rmSync(dir, { recursive: true, force: true });
  } catch {
    // Windows: left for the OS temp cleaner.
  }
});

const write = (files: Record<string, string>) => {
  for (const [name, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true });
    fs.writeFileSync(path.join(dir, name), content);
  }
};
const read = (ecosystem: OsvEcosystem) => resolveVersionSource(dir, ecosystem);
const partials = (ecosystem: OsvEcosystem) => (read(ecosystem).problems ?? []).filter((p) => p.partial === true || (p.skipped ?? 0) > 0);
const problems = (ecosystem: OsvEcosystem) => read(ecosystem).problems ?? [];

