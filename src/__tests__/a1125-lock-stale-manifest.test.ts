describe("F3: Gemfile.lock GEM section with two remotes", () => {
  const lock = (first: string, second: string) => `GEM
  remote: ${first}
  remote: ${second}
  specs:
    acme-internal-auth (1.2.0)
    rack (2.0.1)

PLATFORMS
  ruby

DEPENDENCIES
  acme-internal-auth
  rack (= 2.0.1)

BUNDLED WITH
   2.2.32
`;
  for (const [label, first, second] of [
    ["private first (P1)", "https://gems.example.invalid/", "https://rubygems.org/"],
    ["public first (P2)", "https://rubygems.org/", "https://gems.example.invalid/"],
  ]) {
    it(`${label}: every gem of the section is private`, () => {
      write({ "Gemfile.lock": lock(first, second) });
      const got = read("RubyGems");
      expect((got.privateIndex ?? []).map((p) => p.name).sort()).toEqual(["acme-internal-auth", "rack"]);
      expect(got.privateIndex?.every((p) => /gems\.example\.invalid/.test(p.registry))).toBe(true);
    });
  }

  it("two public remotes stay public", () => {
    write({ "Gemfile.lock": lock("https://rubygems.org/", "https://index.rubygems.org/") });
    expect(read("RubyGems").privateIndex ?? []).toEqual([]);
  });
});

