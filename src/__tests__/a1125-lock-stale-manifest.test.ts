const GEMFILE_LOCK_RAKE = `GEM
  remote: https://rubygems.org/
  specs:
    rake (13.2.1)

PLATFORMS
  ruby

DEPENDENCIES
  rake (= 13.2.1)

BUNDLED WITH
   2.4.22
`;

const PIPFILE_LOCK = (entries: Record<string, string>, develop: Record<string, string> = {}) =>
  JSON.stringify(
    {
      _meta: { hash: { sha256: "0".repeat(64) }, "pipfile-spec": 6, requires: {}, sources: [{ name: "pypi", url: "https://pypi.org/simple", verify_ssl: true }] },
      default: Object.fromEntries(Object.entries(entries).map(([n, v]) => [n, { hashes: [], index: "pypi", version: `==${v}` }])),
      develop: Object.fromEntries(Object.entries(develop).map(([n, v]) => [n, { hashes: [], index: "pypi", version: `==${v}` }])),
    },
    null,
    4,
  );

const POETRY_LOCK = (packages: Array<[string, string, string?]>) =>
  `${packages
    .map(
      ([name, version, deps]) =>
        `[[package]]\nname = "${name}"\nversion = "${version}"\ndescription = ""\ncategory = "main"\noptional = false\npython-versions = "*"\n${deps ? `\n[package.dependencies]\n${deps}\n` : ""}`,
    )
    .join("\n")}\n[metadata]\nlock-version = "1.1"\npython-versions = "^3.8"\ncontent-hash = "${"0".repeat(64)}"\n\n[metadata.files]\n`;

const PDM_LOCK = (packages: Array<[string, string, string[]?]>, groups = '["default"]') =>
  `# This file is @generated by PDM.\n\n[metadata]\ngroups = ${groups}\nstrategy = ["cross_platform"]\nlock_version = "4.4.1"\ncontent_hash = "sha256:${"0".repeat(64)}"\n\n${packages
    .map(([name, version, deps]) => `[[package]]\nname = "${name}"\nversion = "${version}"\nsummary = ""\ndependencies = [\n${(deps ?? []).map((d) => `    "${d}",`).join("\n")}\n]\nfiles = [\n    {file = "${name}-${version}.tar.gz", hash = "sha256:00"},\n]\n`)
    .join("\n")}`;

const COMPOSER_LOCK = (packages: unknown[], dev: unknown[] = []) =>
  JSON.stringify({ _readme: ["x"], "content-hash": "0", packages, "packages-dev": dev, aliases: [], "minimum-stability": "stable", platform: {}, "platform-dev": [] }, null, 4);
const composerPkg = (name: string, version: string, extra: Record<string, unknown> = {}) => ({
  name,
  version,
  source: { type: "git", url: `https://github.com/${name}.git`, reference: "abc" },
  dist: { type: "zip", url: `https://api.github.com/repos/${name}/zipball/abc`, reference: "abc", shasum: "" },
  type: "library",
  ...extra,
});

describe("F1: a lockfile older than its manifest is PARTIAL, as npm's and uv's are", () => {
  it("C1 / S4: a Gemfile gem with no entry in Gemfile.lock", () => {
    write({ Gemfile: "source 'https://rubygems.org'\n\ngem 'rake', '13.2.1'\ngem 'carrierwave', '1.3.1'\n", "Gemfile.lock": GEMFILE_LOCK_RAKE });
    const got = partials("RubyGems");
    expect(got).toHaveLength(1);
    expect(path.basename(got[0].file)).toBe("Gemfile.lock");
    expect(got[0].error).toMatch(/Gemfile declares carrierwave/);
    expect(got[0].error).toMatch(/has no entry for it/);
    // What it holds was still read and checked.
    expect(read("RubyGems").instances.map((i) => i.name)).toEqual(["rake"]);
  });

  it("C2 / S3: a Pipfile package with no entry in Pipfile.lock", () => {
    write({
      Pipfile: '[[source]]\nurl = "https://pypi.org/simple"\nverify_ssl = true\nname = "pypi"\n\n[packages]\nsix = "==1.16.0"\ndjango = "==2.2.0"\n',
      "Pipfile.lock": PIPFILE_LOCK({ six: "1.16.0" }),
    });
    const got = partials("PyPI");
    expect(got).toHaveLength(1);
    expect(path.basename(got[0].file)).toBe("Pipfile.lock");
    expect(got[0].error).toMatch(/Pipfile declares django/);
  });

  it("S1: a Poetry dependency with no entry in poetry.lock", () => {
    write({
      "pyproject.toml": '[tool.poetry]\nname = "demo"\nversion = "0.1.0"\n\n[tool.poetry.dependencies]\npython = "^3.8"\nrequests = "2.19.1"\ndjango = "2.2.0"\n',
      "poetry.lock": POETRY_LOCK([["requests", "2.19.1"]]),
    });
    const got = partials("PyPI");
    expect(got).toHaveLength(1);
    expect(path.basename(got[0].file)).toBe("poetry.lock");
    expect(got[0].error).toMatch(/pyproject\.toml declares django/);
  });

  it("S2: a [project] dependency with no entry in pdm.lock", () => {
    write({
      "pyproject.toml": '[project]\nname = "demo"\nversion = "0.1.0"\ndependencies = [\n    "requests==2.19.1",\n    "django==2.2.0",\n]\n\n[tool.pdm]\ndistribution = false\n',
      "pdm.lock": PDM_LOCK([["requests", "2.19.1"]]),
    });
    const got = partials("PyPI");
    expect(got).toHaveLength(1);
    expect(path.basename(got[0].file)).toBe("pdm.lock");
    expect(got[0].error).toMatch(/pyproject\.toml declares django/);
  });

  it("S5: a composer.json requirement with no entry in composer.lock", () => {
    write({
      "composer.json": JSON.stringify({ name: "demo/demo", require: { php: ">=7.1", "guzzlehttp/guzzle": "6.3.0", "symfony/http-kernel": "4.0.0" } }),
      "composer.lock": COMPOSER_LOCK([composerPkg("guzzlehttp/guzzle", "6.3.0")]),
    });
    const got = partials("Packagist");
    expect(got).toHaveLength(1);
    expect(got[0].error).toMatch(/composer\.json declares symfony\/http-kernel/);
  });

  it("names several, and a dev one too", () => {
    write({
      "composer.json": JSON.stringify({ require: { "a/a": "1.0.0", "b/b": "1", "c/c": "1" }, "require-dev": { "d/d": "1", "e/e": "1" } }),
      "composer.lock": COMPOSER_LOCK([composerPkg("a/a", "1.0.0")], [composerPkg("e/e", "1.0.0")]),
    });
    const got = partials("Packagist");
    expect(got).toHaveLength(1);
    expect(got[0].error).toMatch(/composer\.json declares b\/b, c\/c and d\/d, but this lockfile has no entry for them/);
    expect(got[0].skipped).toBe(3);
  });
});

