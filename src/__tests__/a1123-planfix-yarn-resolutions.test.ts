/**
 * Yarn classic in-range refreshes (zustand: 76 rows "delete every yarn.lock entry that resolves to
 * X, then run yarn install"). Yarn classic has no command that refreshes one package's entries:
 * `yarn upgrade @babel/plugin-transform-modules-systemjs` on zustand's yarn.lock saved nothing
 * (yarn 1.22.22, 2026-11-23). Where the lockfile holds the package on one line only, every copy at or
 * below the target, an exact resolution moves every copy there and nothing else, so the row gets
 * `npm pkg set "resolutions.<name>=<target>"` and `yarn install` and runs in run_order. Another
 * line, or a copy above the target, keeps the hand step.
 */

import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { adv, createHarness, fixedIn, type Harness } from "./helpers/a1119-planner-harness.js";

let h: Harness;
beforeEach(() => {
  h = createHarness();
});
afterEach(() => h.dispose());

const block = (keys: string, version: string, deps = "") => `${keys}:\n  version "${version}"\n  resolved "https://registry.yarnpkg.com/x/-/x-${version}.tgz#a"\n  integrity sha512-x\n${deps}`;

function project(childCopies: Array<[string, string]>) {
  h.ADVISORIES = { child: [adv("GHSA-yyyy-0001", "child", fixedIn("1.0.2"))] };
  h.NPM = {
    par: { latest: "1.0.0", versions: { "1.0.0": { dependencies: { child: "^1.0.0" } } } },
    child: { latest: "1.0.3", versions: { "1.0.0": {}, "1.0.2": {}, "1.0.3": {}, "2.0.0": {}, "2.5.0": {} } },
  };
  h.write("package.json", JSON.stringify({ name: "x", version: "1.0.0", dependencies: { par: "1.0.0" } }));
  h.write(
    "yarn.lock",
    [
      "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n",
      ...childCopies.map(([keys, v]) => block(keys, v)),
      block("par@1.0.0", "1.0.0", '  dependencies:\n    child "^1.0.0"\n'),
    ].join("\n"),
  );
}

describe("a Yarn classic in-range refresh", () => {
  it("with every copy on the target's line at or below it: the exact resolution, in run_order", async () => {
    project([["child@^1.0.0", "1.0.0"]]);
    const { result, step } = await h.plan();
    const row = step("child");
    expect(row.action).toBe("lockfile_refresh");
    expect(row.commands).toEqual([
      { dir: ".", run: 'npm pkg set "resolutions.child=1.0.3"' },
      { dir: ".", run: "yarn install" },
    ]);
    expect(row.reasons.join(" ")).toMatch(/Yarn classic has no command that refreshes one package's yarn\.lock entries/);
    expect(result.run_order.map((s: { run: string }) => s.run)).toEqual(['npm pkg set "resolutions.child=1.0.3"', "yarn install"]);
  });

  it("with a copy on another line, or above the release a refresh resolves to: the hand step only", async () => {
    // 1.0.3, the newest release on the line, is what the resolution forces now (a1125 w2): a copy at it is no longer above it.
    for (const other of ["2.5.0"]) {
      project([
        ["child@^1.0.0", "1.0.0"],
        [`child@^${other}`, other],
      ]);
      const { result, step } = await h.plan();
      expect(step("child", "1.0.0").commands).toEqual([]);
      expect(result.run_order).toEqual([]);
      h.dispose();
      h = createHarness();
    }
  });
});
