/**
 * A Python, Go, Cargo, Ruby or PHP file that exists but cannot be read to its end is a named
 * problem (unreadable or partial), never "nothing here" and never a complete read. A file that
 * is absent stays absent, and a healthy file reports nothing.
 */
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import Database from "better-sqlite3";
import { cargoDeclaredPackages, resolveVersionSource } from "../live/lockfile-parsers.js";
import { pyprojectRequirements } from "../live/pyproject-requirements.js";
import { LiveIntelligence } from "../live/index.js";
import { executeVulnerabilityScan } from "../tools/vulnerability-scan.js";
import type { OsvEcosystem } from "../live/types.js";

let dir: string;
const write = (rel: string, content: string) => {
  const file = path.join(dir, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return file;
};
/** A directory where a file is expected: every read of it fails (EISDIR), on every platform. */
const unreadable = (rel: string) => fs.mkdirSync(path.join(dir, rel), { recursive: true });
const read = (ecosystem: OsvEcosystem) => resolveVersionSource(dir, ecosystem);
const problemsOf = (ecosystem: OsvEcosystem) => (read(ecosystem).problems ?? []).map((p) => ({ ...p, file: path.basename(p.file) }));
const names = (ecosystem: OsvEcosystem) => read(ecosystem).instances.map((i) => `${i.name}@${i.version}`).sort();

beforeEach(() => {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), "a1119-damaged-"));
});
afterEach(() => fs.rmSync(dir, { recursive: true, force: true }));

