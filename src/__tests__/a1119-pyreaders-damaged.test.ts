describe("whole files report nothing, and absent files stay absent", () => {
  it("whole lockfiles of every ecosystem read with no problem", () => {
    write("poetry.lock", POETRY_LOCK);
    write("Gemfile.lock", GEMFILE_LOCK);
    write("go.mod", GO_MOD);
    write("Cargo.toml", CARGO_TOML);
    write("Cargo.lock", CARGO_LOCK);
    expect(problemsOf("PyPI")).toEqual([]);
    expect(problemsOf("RubyGems")).toEqual([]);
    expect(problemsOf("Go")).toEqual([]);
    expect(problemsOf("crates.io")).toEqual([]);
    expect(names("crates.io")).toEqual(["memchr@2.7.0", "regex@1.10.0", "serde_json@1.0.100", "tempfile@3.8.0"]);
  });

  it("a whole uv.lock beside its pyproject.toml reads with no problem", () => {
    write("pyproject.toml", '[project]\nname = "fx"\nversion = "0.1.0"\ndependencies = ["requests==2.19.1"]\n');
    write("uv.lock", UV_LOCK);
    expect(problemsOf("PyPI")).toEqual([]);
    expect(names("PyPI")).toEqual(["certifi@2018.1.18", "idna@2.7", "requests@2.19.1", "urllib3@1.23"]);
  });

  it("a poetry.lock of a project with no dependencies is not damaged", () => {
    write("poetry.lock", 'package = []\n\n[metadata]\nlock-version = "2.0"\npython-versions = "^3.8"\ncontent-hash = "00"\n');
    expect(problemsOf("PyPI")).toEqual([]);
  });

  it("a Gemfile.lock of a project with no gems is not damaged", () => {
    write("Gemfile.lock", "GEM\n  specs:\n\nPLATFORMS\n  ruby\n\nDEPENDENCIES\n\nBUNDLED WITH\n   2.4.10\n");
    expect(problemsOf("RubyGems")).toEqual([]);
  });

  it("an empty directory has no source and no problem, for every ecosystem", () => {
    for (const ecosystem of ["PyPI", "Go", "crates.io", "RubyGems", "Packagist"] as const) {
      const source = read(ecosystem);
      expect(source.source).toBeNull();
      expect(source.problems ?? []).toEqual([]);
    }
  });
});

describe("a scan over a damaged file is never a clean result", () => {
  let priorOffline: string | undefined;
  beforeEach(() => {
    priorOffline = process.env.FOURDA_OFFLINE;
    delete process.env.FOURDA_OFFLINE;
    vi.stubGlobal("fetch", async (input: string | URL, init?: RequestInit) => {
      const url = String(input);
      if (url.endsWith("/v1/querybatch")) {
        const { queries } = JSON.parse(String(init?.body)) as { queries: unknown[] };
        return new Response(JSON.stringify({ results: queries.map(() => ({})) }), { status: 200 });
      }
      throw new TypeError(`fetch failed (${url})`);
    });
  });
  afterEach(() => {
    vi.unstubAllGlobals();
    if (priorOffline === undefined) delete process.env.FOURDA_OFFLINE;
    else process.env.FOURDA_OFFLINE = priorOffline;
  });
  const scan = async () =>
    (await executeVulnerabilityScan(null, { project_path: dir, response_format: "detailed" }, new LiveIntelligence(new Database(":memory:")))) as Record<string, any>;

  it("a truncated Pipfile.lock: listed as unreadable, no totals, and no 'nothing was found here'", async () => {
    write("Pipfile.lock", PIPFILE_LOCK.slice(0, 150));
    const result = await scan();
    expect(result.coverage.complete).toBe(false);
    expect(result.coverage.unreadable_lockfiles).toEqual([expect.objectContaining({ path: "Pipfile.lock", error: expect.stringMatching(/invalid JSON/) })]);
    expect(result.total_vulnerable_packages).toBeNull();
    expect(JSON.stringify(result)).not.toMatch(/No manifest or lockfile of a supported ecosystem was found/);
  });

  it("an unreadable Cargo.lock: listed as unreadable, not counted as a lockfile that was read", async () => {
    write("Cargo.toml", CARGO_TOML);
    unreadable("Cargo.lock");
    const result = await scan();
    expect(result.coverage.unreadable_lockfiles).toEqual([expect.objectContaining({ path: "Cargo.lock" })]);
    expect(result.total_vulnerable_packages).toBeNull();
    expect(JSON.stringify(result)).not.toMatch(/Lock file found but no dependency versions could be resolved/);
  });

  it("an unreadable requirements.txt: listed as unreadable, not 'no lock file'", async () => {
    unreadable("requirements.txt");
    const result = await scan();
    expect(result.coverage.unreadable_lockfiles).toEqual([expect.objectContaining({ path: "requirements.txt" })]);
    expect(result.total_vulnerable_packages).toBeNull();
    expect(JSON.stringify(result)).not.toMatch(/Found requirements\.txt but no lock file/);
  });

  it("an unreadable Cargo.toml beside a healthy npm project is still named", async () => {
    write("package.json", JSON.stringify({ name: "x", dependencies: { lodash: "4.17.21" } }));
    write("package-lock.json", JSON.stringify({ name: "x", lockfileVersion: 3, packages: { "": { name: "x", dependencies: { lodash: "4.17.21" } }, "node_modules/lodash": { version: "4.17.21" } } }));
    unreadable("Cargo.toml");
    const result = await scan();
    expect(result.total_dependencies_scanned).toBe(1);
    expect(result.coverage.complete).toBe(false);
    expect(result.coverage.unreadable_lockfiles).toEqual([expect.objectContaining({ path: "Cargo.toml", error: expect.stringMatching(/could not be read/) })]);
  });

  it("a poetry.lock cut before [metadata]: what was read is scanned, and the file is listed as partial", async () => {
    write("poetry.lock", POETRY_LOCK.slice(0, POETRY_LOCK.indexOf("[metadata]")));
    const result = await scan();
    expect(result.total_dependencies_scanned).toBe(2);
    expect(result.coverage.complete).toBe(false);
    expect(result.coverage.partial_lockfiles).toEqual([expect.objectContaining({ path: "poetry.lock" })]);
  });
});
