const CARGO_TOML = `[package]
name = "zapp"
version = "0.1.0"
edition = "2021"

[dependencies]
regex = "1"
serde_json = { version = "1" }

[dev-dependencies]
tempdir = { package = "tempfile", version = "3" }
`;

const cargoPackage = (name: string, version: string, deps: string[] = [], registry = true) =>
  `[[package]]\nname = "${name}"\nversion = "${version}"\n${registry ? 'source = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "00"\n' : ""}${
    deps.length > 0 ? `dependencies = [\n${deps.map((d) => ` "${d}",\n`).join("")}]\n` : ""
  }`;
const CARGO_LOCK_HEAD = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n";
const CARGO_PACKAGES = [
  cargoPackage("memchr", "2.7.0"),
  cargoPackage("regex", "1.10.0", ["memchr"]),
  cargoPackage("serde_json", "1.0.100"),
  cargoPackage("tempfile", "3.8.0"),
  cargoPackage("zapp", "0.1.0", ["regex", "serde_json", "tempfile"], false),
];
const CARGO_LOCK = CARGO_LOCK_HEAD + CARGO_PACKAGES.join("\n");

const GEMFILE_LOCK = `GEM
  remote: https://rubygems.org/
  specs:
    rack (2.0.7)
    rails (6.0.0)
      rack (~> 2.0)

PLATFORMS
  ruby

DEPENDENCIES
  rails (~> 6.0.0)

BUNDLED WITH
   2.0.2
`;

const GO_MOD = "module github.com/golang/example\n\ngo 1.21\n\nrequire (\n\tgolang.org/x/text v0.3.0\n\tgolang.org/x/crypto v0.1.0\n\tgolang.org/x/net v0.7.0\n)\n";

describe("JSON lockfiles are validated as JSON whatever their name or length", () => {
  it("a short truncated Pipfile.lock is invalid JSON, not an absent lockfile", () => {
    write("Pipfile.lock", PIPFILE_LOCK.slice(0, 150));
    expect(read("PyPI").instances).toEqual([]);
    const problems = problemsOf("PyPI");
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ file: "Pipfile.lock", ecosystem: "PyPI" });
    expect(problems[0].error).toMatch(/invalid JSON/);
  });

  it("a short truncated composer.lock is named too", () => {
    write("composer.lock", '{"packages": [{"name": "guzzlehttp/guzzle", "version": "6.5.0"},');
    const problems = problemsOf("Packagist");
    expect(problems).toHaveLength(1);
    expect(problems[0].file).toBe("composer.lock");
    expect(problems[0].error).toMatch(/JSON/);
  });

  it("a Pipfile.lock that is JSON but no object of sections is named, never read as empty", () => {
    write("Pipfile.lock", '["django==2.2.0"]\n');
    expect(problemsOf("PyPI")).toEqual([expect.objectContaining({ file: "Pipfile.lock", error: expect.stringMatching(/not a Pipfile\.lock/) })]);
  });

  it("one malformed entry does not drop the entries that can be read, and is said", () => {
    write("Pipfile.lock", JSON.stringify({ _meta: { sources: [] }, default: { django: { version: "==2.2.0" }, broken: { version: 5 }, pyyaml: { version: "==5.1" } }, develop: {} }));
    expect(names("PyPI")).toEqual(["django@2.2.0", "pyyaml@5.1"]);
    expect(problemsOf("PyPI")).toEqual([expect.objectContaining({ file: "Pipfile.lock", skipped: 1, error: expect.stringMatching(/broken/) })]);
  });

  it("the whole Pipfile.lock reads with no problem", () => {
    write("Pipfile.lock", PIPFILE_LOCK);
    expect(names("PyPI")).toEqual(["django@2.2.0", "pyyaml@5.1"]);
    expect(problemsOf("PyPI")).toEqual([]);
  });

  it("an empty but valid Pipfile.lock is a project with no dependencies, not a problem", () => {
    write("Pipfile.lock", '{"_meta": {"sources": []}, "default": {}, "develop": {}}\n');
    expect(problemsOf("PyPI")).toEqual([]);
  });
});

describe("a file that cannot be read is a problem, not a read", () => {
  it("an unreadable Cargo.lock is not counted as the file the versions came from", () => {
    write("Cargo.toml", CARGO_TOML);
    unreadable("Cargo.lock");
    const source = read("crates.io");
    expect(source.source).toBeNull();
    expect(source.kind).toBeNull();
    const problems = problemsOf("crates.io");
    expect(problems).toHaveLength(1);
    expect(problems[0].file).toBe("Cargo.lock");
    expect(problems[0].error).toMatch(/could not be read/);
  });

  it("an unreadable requirements file is named, and the readable one beside it is still read", () => {
    unreadable("requirements.txt");
    write("requirements-dev.txt", "pytest==5.4.2\n");
    expect(names("PyPI")).toEqual(["pytest@5.4.2"]);
    const problems = problemsOf("PyPI");
    expect(problems).toHaveLength(1);
    expect(problems[0].file).toBe("requirements.txt");
    expect(problems[0].error).toMatch(/could not be read/);
  });

  it("an include that cannot be read is named: its pins were not checked", () => {
    write("requirements.txt", "-r base.txt\nrequests==2.19.1\n");
    unreadable("base.txt");
    expect(names("PyPI")).toEqual(["requests@2.19.1"]);
    const problems = problemsOf("PyPI");
    expect(problems).toHaveLength(1);
    expect(problems[0].file).toBe("base.txt");
    expect(problems[0].error).toMatch(/requirements\.txt/);
    expect(problems[0].error).toMatch(/could not be read/);
  });

  it("an unreadable Cargo.toml with no Cargo.lock is named", () => {
    unreadable("Cargo.toml");
    const problems = problemsOf("crates.io");
    expect(problems).toHaveLength(1);
    expect(problems[0].file).toBe("Cargo.toml");
    expect(problems[0].error).toMatch(/could not be read/);
  });

  it("an unreadable go.sum is named when the build list needs it (go before 1.17)", () => {
    write("go.mod", "module example.com/app\n\ngo 1.16\n\nrequire golang.org/x/text v0.3.0\n");
    unreadable("go.sum");
    expect(names("Go")).toEqual(["golang.org/x/text@v0.3.0"]);
    expect(problemsOf("Go")).toEqual([expect.objectContaining({ file: "go.sum", error: expect.stringMatching(/could not be read/) })]);
  });

  it("a go.mod with no module directive and no requirement is not read as a project with no dependencies", () => {
    write("go.mod", "requ");
    expect(read("Go").source).toBeNull();
    expect(problemsOf("Go")).toEqual([expect.objectContaining({ file: "go.mod", error: expect.stringMatching(/module/) })]);
  });

  it("an unreadable pyproject.toml is named when no lockfile was read in its place", () => {
    unreadable("pyproject.toml");
    write("requirements.txt", "requests==2.19.1\n");
    expect(names("PyPI")).toEqual(["requests@2.19.1"]);
    expect(problemsOf("PyPI")).toEqual([expect.objectContaining({ file: "pyproject.toml", error: expect.stringMatching(/could not be read/) })]);
  });

  it("an include that does not exist is said as not found, never read as an empty file", () => {
    write("requirements.txt", "-r generated.txt\nrequests==2.19.1\n");
    expect(names("PyPI")).toEqual(["requests@2.19.1"]);
    const problems = problemsOf("PyPI");
    expect(problems).toHaveLength(1);
    expect(problems[0].file).toBe("generated.txt");
    expect(problems[0].error).toMatch(/`-r generated\.txt` in requirements\.txt was not found, so the pins in it were not checked/);
  });
});

describe("truncation that still parses is reported as a partial read", () => {
  it("poetry.lock with no [metadata] table at its end", () => {
    write("poetry.lock", POETRY_LOCK.slice(0, POETRY_LOCK.indexOf("[metadata]")));
    expect(names("PyPI")).toEqual(["django@2.2.0", "pyyaml@5.1"]);
    const problems = problemsOf("PyPI");
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ file: "poetry.lock", partial: true });
    expect(problems[0].error).toMatch(/\[metadata\]/);
  });

  it("a few lines of a poetry.lock that give no package at all", () => {
    write("poetry.lock", '[[package]\nname = "django"\nversion = "2.2.0"\n');
    expect(read("PyPI").instances).toEqual([]);
    const problems = problemsOf("PyPI");
    expect(problems).toHaveLength(1);
    expect(problems[0].file).toBe("poetry.lock");
    expect(problems[0].error).toMatch(/\[metadata\]/);
  });

  it("Gemfile.lock with no DEPENDENCIES section", () => {
    write("Gemfile.lock", GEMFILE_LOCK.slice(0, GEMFILE_LOCK.indexOf("PLATFORMS")));
    expect(names("RubyGems")).toEqual(["rack@2.0.7", "rails@6.0.0"]);
    const problems = problemsOf("RubyGems");
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ file: "Gemfile.lock", partial: true });
    expect(problems[0].error).toMatch(/DEPENDENCIES/);
  });

  it("a Gemfile.lock cut before its first gem", () => {
    write("Gemfile.lock", "GEM\n  remote: https://rubygems.org/\n  specs:\n");
    expect(problemsOf("RubyGems")).toEqual([expect.objectContaining({ file: "Gemfile.lock", error: expect.stringMatching(/DEPENDENCIES/) })]);
  });

  it("go.mod cut inside its require block", () => {
    write("go.mod", GO_MOD.slice(0, GO_MOD.indexOf("\tgolang.org/x/net")));
    expect(names("Go")).toEqual(["golang.org/x/crypto@v0.1.0", "golang.org/x/text@v0.3.0"]);
    const problems = problemsOf("Go");
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ file: "go.mod", partial: true });
    expect(problems[0].error).toMatch(/require \(/);
  });

  it("uv.lock cut between tables: a package another one depends on has no table", () => {
    write("uv.lock", UV_LOCK.slice(0, UV_LOCK.indexOf('[[package]]\nname = "urllib3"')));
    const problems = problemsOf("PyPI");
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ file: "uv.lock", partial: true });
    expect(problems[0].error).toMatch(/urllib3/);
  });

  it("uv.lock with no entry for a dependency pyproject.toml declares", () => {
    write("pyproject.toml", '[project]\nname = "fx"\nversion = "0.1.0"\ndependencies = [\n  "requests==2.19.1",\n  "tomli>=2; python_version < \'3.11\'",\n]\n');
    // Cut after the first table: what is left is whole, and names nothing that is missing.
    write("uv.lock", UV_LOCK.slice(0, UV_LOCK.indexOf('[[package]]\nname = "fx"')));
    expect(names("PyPI")).toEqual(["certifi@2018.1.18"]);
    const problems = problemsOf("PyPI");
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ file: "uv.lock", partial: true });
    expect(problems[0].error).toMatch(/requests/);
    // A requirement behind an environment marker need not be locked: never named as missing.
    expect(problems[0].error).not.toMatch(/tomli/);
  });

  it("Cargo.lock with no entry for a dependency Cargo.toml declares", () => {
    write("Cargo.toml", CARGO_TOML);
    // Cut after regex: the tables left are whole and every dependency they name has one.
    write("Cargo.lock", CARGO_LOCK_HEAD + CARGO_PACKAGES.slice(0, 2).join("\n"));
    expect(names("crates.io")).toEqual(["memchr@2.7.0", "regex@1.10.0"]);
    const problems = problemsOf("crates.io");
    expect(problems).toHaveLength(1);
    expect(problems[0]).toMatchObject({ file: "Cargo.lock", partial: true });
    // serde_json is declared; tempfile is declared under another name (`package = "tempfile"`).
    expect(problems[0].error).toMatch(/serde_json/);
    expect(problems[0].error).toMatch(/tempfile/);
    expect(problems[0].error).not.toMatch(/tempdir/);
  });

  it("a Cargo.lock with no [[package]] table is not a lockfile cargo wrote", () => {
    write("Cargo.toml", CARGO_TOML);
    write("Cargo.lock", "# This file is automatically @generated by Cargo.\nversion = 3\n");
    const problems = problemsOf("crates.io");
    expect(problems).toHaveLength(1);
    expect(problems[0].file).toBe("Cargo.lock");
    expect(problems[0].error).toMatch(/\[\[package\]\]/);
  });
});

