/**
 * zustand (yarn classic): one yarn.lock entry `"@babel/core@^7.11.6", "@babel/core@^7.12.3",
 * "@babel/core@^7.19.6"` resolves to 7.19.6; the manifest declares "^7.19.6". `yarn upgrade
 * @babel/core` re-resolved only the declared range and the two transitive ranges kept 7.19.6, so
 * the step ran without effect (yarn 1.22.22, 2026-11-23). The row now gives the hand step that
 * moves every range, and run_order leaves it out.
 */

import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { adv, createHarness, fixedIn, type Harness } from "./helpers/a1119-planner-harness.js";

let h: Harness;
beforeEach(() => {
  h = createHarness();
});
afterEach(() => h.dispose());

function project(header: string) {
  h.ADVISORIES = { "@babel/core": [adv("GHSA-4x5r-pxfx-6jf8", "@babel/core", fixedIn("7.20.0"))] };
  h.NPM = {
    "@babel/core": { latest: "7.20.0", versions: { "7.19.6": {}, "7.20.0": {} } },
    "jest-thing": { latest: "1.0.0", versions: { "1.0.0": { dependencies: { "@babel/core": "^7.11.6" } } } },
  };
  h.write("package.json", JSON.stringify({ name: "x", version: "1.0.0", dependencies: { "@babel/core": "^7.19.6", "jest-thing": "1.0.0" } }));
  h.write(
    "yarn.lock",
    [
      "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n",
      `${header}:\n  version "7.19.6"\n  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.19.6.tgz#a"\n  integrity sha512-core\n`,
      '\njest-thing@1.0.0:\n  version "1.0.0"\n  resolved "https://registry.yarnpkg.com/jest-thing/-/jest-thing-1.0.0.tgz#b"\n  integrity sha512-jest\n  dependencies:\n    "@babel/core" "^7.11.6"\n',
    ].join(""),
  );
}

describe("Yarn classic: one entry keyed by the declared range and transitive ones", () => {
  it("gives the hand step that moves every range, not `yarn upgrade`", async () => {
    project('"@babel/core@^7.11.6", "@babel/core@^7.12.3", "@babel/core@^7.19.6"');
    const { result, step } = await h.plan();
    const row = step("@babel/core");
    expect(row.commands).toEqual([]);
    expect(row.upgradeInstructions).toEqual([{ dir: ".", instruction: 'delete every yarn.lock entry that resolves to @babel/core (keys "@babel/core@…" and alias keys "…@npm:@babel/core@…"), then run yarn install' }]);
    expect(row.reasons.join(" ")).toMatch(/yarn\.lock holds @babel\/core 7\.19\.6 under one entry keyed by 3 ranges/);
    expect(result.run_order.map((s: { run: string }) => s.run)).not.toContain("yarn upgrade @babel/core");
  });

  it("keeps `yarn upgrade` when the entry is keyed by the declared range alone", async () => {
    project('"@babel/core@^7.19.6"');
    const { step } = await h.plan();
    expect(step("@babel/core").commands).toEqual([{ dir: ".", run: "yarn upgrade @babel/core" }]);
  });
});
