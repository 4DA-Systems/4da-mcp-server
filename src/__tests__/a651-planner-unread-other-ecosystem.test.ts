/**
 * upgrade_planner says `vulnerabilityDataAvailable: true` only when the scan it plans from is
 * complete. 6.5.0 set it false only when NOTHING could be read: a project whose npm lockfile was
 * read beside a Cargo.lock with merge-conflict markers, an unparseable poetry.lock or a Cargo.lock
 * cut off part-way said `vulnerabilityDataAvailable: true`, while vulnerability_scan on the same
 * project said `coverage.complete: false` and the plan's own summary named the file. The crates or
 * PyPI packages in that file were never checked, so the plan is not CVE-aware for them.
 */

import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { adv, createHarness, fixedIn, type Harness } from "./helpers/a1119-planner-harness.js";

let h: Harness;
beforeEach(() => {
  h = createHarness();
  h.ADVISORIES = { tar: [adv("GHSA-r6q2-hw4h-h46w", "tar", fixedIn("7.5.21"))] };
  h.NPM = { tar: { latest: "7.5.21", versions: { "6.1.15": {}, "7.5.21": {} } } };
  // A readable npm project at the root: the plan has rows to give.
  h.npmProject({ tar: "~6.1.11" }, {}, { tar: { version: "6.1.15" } });
});
afterEach(() => h.dispose());

const CARGO_TOML = '[package]\nname = "svc"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\nitoa = "1"\n';
const CARGO_LOCK_HEAD = "# This file is automatically @generated by Cargo.\nversion = 3\n\n";

describe("a lockfile of another ecosystem that was not read", () => {
  it("a Cargo.lock with merge-conflict markers: vulnerabilityDataAvailable is false and the summary leads with it", async () => {
    h.write("svc/Cargo.toml", CARGO_TOML);
    h.write(
      "svc/Cargo.lock",
      `${CARGO_LOCK_HEAD}[[package]]\nname = "itoa"\n<<<<<<< HEAD\nversion = "1.0.10"\n=======\nversion = "1.0.11"\n>>>>>>> other\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n\n[[package]]\nname = "svc"\nversion = "0.1.0"\ndependencies = [\n "itoa",\n]\n`,
    );
    const scan = await h.scan();
    expect(scan.coverage.complete).toBe(false);
    const { result } = await h.plan();
    expect(result.vulnerabilityDataAvailable).toBe(false);
    expect(result.summary).toMatch(/^NOT CHECKED/);
    expect(result.summary).toMatch(/Cargo\.lock/);
  });

  it("an unparseable poetry.lock: vulnerabilityDataAvailable is false", async () => {
    h.write("py/pyproject.toml", '[tool.poetry]\nname = "py"\nversion = "0.1.0"\n\n[tool.poetry.dependencies]\npython = "^3.11"\nrequests = "^2.31"\n');
    h.write("py/poetry.lock", '[[package]]\nname = "requests"\nversion = "2.31.0"\n[[package\nname = = "idna"\n\u0000\u0000garbage\n');
    const scan = await h.scan();
    const { result } = await h.plan();
    // The plan agrees with the scan: a scan that is not complete is no CVE-aware plan.
    if (scan.coverage.complete === false) expect(result.vulnerabilityDataAvailable).toBe(false);
    expect(result.vulnerabilityDataAvailable).toBe(false);
    expect(result.summary).toMatch(/^NOT CHECKED/);
  });

  it("a Cargo.lock cut off part-way (read in part): vulnerabilityDataAvailable is false", async () => {
    h.write("svc/Cargo.toml", CARGO_TOML);
    h.write("svc/Cargo.lock", `${CARGO_LOCK_HEAD}[[package]]\nname = "itoa"\nversion = "1.0.10"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n\n[[package]]\nname = "sv`);
    const scan = await h.scan();
    const { result } = await h.plan();
    if (scan.coverage.complete === false) expect(result.vulnerabilityDataAvailable).toBe(false);
    expect(result.vulnerabilityDataAvailable).toBe(false);
  });

  it("control: the npm lockfile alone gives vulnerabilityDataAvailable true", async () => {
    const scan = await h.scan();
    expect(scan.coverage.complete).toBe(true);
    const { result } = await h.plan();
    expect(result.vulnerabilityDataAvailable).toBe(true);
    expect(result.summary).not.toMatch(/NOT CHECKED/);
  });
});
